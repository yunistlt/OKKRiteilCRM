// ============================================================================
// Рабочий календарь месяца — ЕДИНЫЙ источник для расчёта (metrics.ts, сервер) и
// для интерфейса (табель отработанных дней, клиент). Отдельный модуль, потому
// что metrics.ts тянет supabase и в браузер его импортировать нельзя.
//
// ВАЖНО: норма считается как «все пн–пт», государственные праздники НЕ
// учитываются — источника производственного календаря в системе пока нет.
// Для месяцев с праздниками (январь, май, ноябрь) норма получается завышенной,
// а значит оклад у отсутствовавших урезается сильнее положенного. Когда появится
// справочник праздников — вычитать их надо здесь, и это автоматически
// подхватят и расчёт, и табель.
// ============================================================================

/** Рабочих дней (пн–пт) в месяце. Праздники не вычитаются — см. шапку файла. */
export function businessDaysInMonth(year: number, month: number): number {
    let count = 0;
    const daysInMonth = new Date(year, month, 0).getDate();
    for (let d = 1; d <= daysInMonth; d++) {
        const dow = new Date(year, month - 1, d).getDay();
        if (dow !== 0 && dow !== 6) count++;
    }
    return count;
}
