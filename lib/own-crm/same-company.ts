/**
 * Одно ли это юрлицо.
 *
 * Сравниваем по буквам и цифрам, без кавычек, пробелов и организационной
 * формы: «ООО "Ромашка"» и «Общество с ограниченной ответственностью Ромашка»
 * — одна компания.
 *
 * Нужно там, где данные берутся из заказа: в заказе клиента может стоять
 * совсем другой контрагент. 05.10.2026 в карточке «ООО Ресурс Комплект Сервис»
 * показывались реквизиты и ИНН «Росхимзащиты» — по ним выставили бы счёт.
 */
export function sameCompany(left: string | null | undefined, right: string | null | undefined): boolean {
    const bare = (value: string) => String(value ?? '')
        .toLowerCase()
        .replace(/\b(ооо|оао|зао|ао|пао|ип|нао|общество с ограниченной ответственностью|акционерное общество)\b/g, '')
        .replace(/[^a-zа-яё0-9]+/gi, '');

    const a = bare(left ?? '');
    const b = bare(right ?? '');
    if (!a || !b) return false;
    return a === b || a.includes(b) || b.includes(a);
}
