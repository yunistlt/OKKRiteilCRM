/**
 * Местное время клиента по его номеру телефона.
 *
 * Евгения Матвеева 05.10.2026: «можно поставить, чтобы высвечивалось реальное
 * время клиента, как в ритейле?» Звонить во Владивосток в 17:00 по Москве —
 * это звонок в полночь, и менеджер должен видеть это до набора.
 *
 * Считаем по коду города стационарного номера (ABC-коды 3xx/4xx/8xx): он
 * привязан к месту намертво. У мобильных (9xx) привязки нет — номер
 * переносится между регионами, поэтому для них время не показываем вовсе,
 * вместо того чтобы показать неверное.
 *
 * Дадата здесь не помощник: на бесплатном тарифе подсказок поле `timezone`
 * приходит пустым (проверено 05.10.2026).
 */

