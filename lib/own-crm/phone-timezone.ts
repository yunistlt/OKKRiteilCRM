export type ClientTime = {
    /** Смещение от Москвы: «+2», «−1», «» для московского. */
    shift: string;
    /** Часы и минуты у клиента прямо сейчас. */
    time: string;
};

/** Цифры номера без разделителей, приведённые к виду 7XXXXXXXXXX. */
function digits(phone: string): string {
    const only = String(phone ?? '').replace(/\D+/g, '');
    if (only.length === 11 && (only.startsWith('8') || only.startsWith('7'))) return `7${only.slice(1)}`;
    if (only.length === 10) return `7${only}`;
    return only;
}

/** Смещение клиента от Москвы в часах или null, если по номеру не определить. */
export function moscowShift(phone: string): number | null {
    const value = digits(phone);
    if (value.length !== 11) return null;

    const code = value.slice(1, 4);
    // Мобильный номер о месте ничего не говорит — переносится между регионами.
    if (code.startsWith('9')) return null;

    const shift = BY_CODE[code];
    return typeof shift === 'number' ? shift : null;
}

/** Местное время клиента к показу рядом с телефоном. */
export function clientTime(phone: string, now = new Date()): ClientTime | null {
    const shift = moscowShift(phone);
    if (shift === null) return null;

    const moscow = new Date(now.toLocaleString('en-US', { timeZone: 'Europe/Moscow' }));
    moscow.setHours(moscow.getHours() + shift);

    const hh = String(moscow.getHours()).padStart(2, '0');
    const mm = String(moscow.getMinutes()).padStart(2, '0');

    return {
        shift: shift === 0 ? '' : `${shift > 0 ? '+' : '−'}${Math.abs(shift)} ч к Москве`,
        time: `${hh}:${mm}`,
    };
}
