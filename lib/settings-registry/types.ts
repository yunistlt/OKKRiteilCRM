/**
 * Что вообще в этом сервисе можно покрутить.
 *
 * До сих пор каждая подсистема знала свои настройки сама: бот-РОП — 37 ключей в
 * sales_rop_settings, мотивация — версионируемый по датам salary_config,
 * качество — строки okk_rules. Человек, чтобы поднять нагрузку на отдел на 5%,
 * должен был помнить, что это ключ load_factor, что он в боте-РОПе и что
 * границы 0.5–2.0. Тамара не знала и этого: её инструменты были только на
 * чтение и только про Штаб.
 *
 * Реестр даёт одно место, где у каждой ручки есть человеческое имя, объяснение
 * последствий и способ её прочитать и применить. Модель ищет по этому реестру
 * так же, как искал бы человек: словами, а не ключами.
 *
 * Почему реестр, а не прямой SQL: Тамара пишет не значение в таблицу, а
 * ПРЕДЛОЖЕНИЕ изменения. Применяет его владелец нажатием в интерфейсе, и
 * применяет уже код подсистемы — тот же, что стоит за её собственным экраном
 * настроек, со всеми его проверками. Модель не обходит валидацию, а становится
 * ещё одним способом до неё добраться.
 */

/** Как показать и как проверить значение. */
export type KnobKind =
    | 'number' // целое: количество задач, дней
    | 'factor' // множитель с дробной частью: нагрузка 1.05
    | 'money' // рубли
    | 'toggle' // да/нет
    | 'text'
    | 'ids' // список идентификаторов через запятую
    | 'codes' // список кодов справочника
    | 'json'; // сложная структура: тиры, правила

export type ModuleId = 'sales_rop' | 'salary' | 'salary_plan' | 'okk';

export const MODULE_TITLES: Record<ModuleId, string> = {
    sales_rop: 'Бот-РОП: ежедневные задачи отдела продаж',
    salary: 'Мотивация: ставки и коэффициенты зарплаты',
    salary_plan: 'План продаж: цели месяца',
    okk: 'Качество: правила и штрафы ОКК',
};

/** Описание одной ручки — то, что видит модель и человек. */
export type Knob = {
    /** Устойчивый адрес вида `sales_rop.load_factor`. По нему ручку и предлагают. */
    id: string;
    module: ModuleId;
    title: string;
    /** Что будет, если сдвинуть. Пишется для человека, читается моделью. */
    hint: string;
    kind: KnobKind;
    unit?: string;
    /** Группа внутри подсистемы — «Нагрузка отдела», «Конверсия». */
    group: string;
    /**
     * Действует не сразу, а с даты (мотивация). Такую ручку нельзя менять
     * задним числом молча: предложение обязано нести дату.
     */
    effectiveDated?: boolean;
};

/** Ручка вместе с текущим значением. */
export type KnobValue = Knob & {
    /** Текущее значение в человекочитаемом виде. Пустая строка — не задано. */
    value: string;
    /** Сырое значение для сложных ключей: модель должна видеть структуру. */
    raw?: unknown;
};

export type ProposalOptions = {
    /** С какой даты (для версионируемых ручек), YYYY-MM-DD. */
    effectiveFrom?: string;
};

export type ApplyOptions = ProposalOptions & {
    /** Кто подтвердил — попадёт в аудит подсистемы. */
    actor: string | null;
    /** Зачем меняли — формулировка Тамары, попадает в примечание к версии. */
    note?: string;
};

/**
 * Адаптер подсистемы.
 *
 * Читать умеет любой, применять — только он сам: правка salary_config это новая
 * версия по дате, правка sales_rop_settings — upsert по ключу, и сводить их к
 * одному «записать строку» значило бы потерять смысл каждой.
 */
export type ModuleAdapter = {
    id: ModuleId;
    /** Все ручки подсистемы с текущими значениями. */
    list(): Promise<KnobValue[]>;
    /**
     * Проверить предлагаемое значение ДО показа человеку. Возвращает то, как
     * оно будет выглядеть после применения, или бросает с понятным текстом.
     * Вызывается дважды: когда Тамара предлагает и когда человек подтверждает,
     * — между этими моментами настройка могла измениться.
     */
    validate(knobId: string, value: string, opts: ProposalOptions): Promise<string>;
    /** Применить. Вызывается только после подтверждения человеком. */
    apply(knobId: string, value: string, opts: ApplyOptions): Promise<void>;
};

/** Ключ ручки без имени подсистемы: `sales_rop.load_factor` → `load_factor`. */
export function knobKey(knobId: string): string {
    const i = knobId.indexOf('.');
    return i === -1 ? knobId : knobId.slice(i + 1);
}

export function knobModule(knobId: string): ModuleId | null {
    const i = knobId.indexOf('.');
    if (i === -1) return null;
    const m = knobId.slice(0, i);
    return m in MODULE_TITLES ? (m as ModuleId) : null;
}
