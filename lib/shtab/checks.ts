// Проверки, которыми Тамара ловит типовые ошибки разбора.
//
// Это не ИИ и не претендует им быть: разбор ведёт владелец, а здесь работают
// правила из методички, применённые к тому, что он написал прямо сейчас. Задача —
// поймать три ошибки, которые в методичке названы прямо и которые дороже всего
// стоят: причина вне организации, ярлык вместо ситуации, обобщённый ресурс.
//
// Русские тексты здесь — это реплики наставницы, а не подписи справочников:
// они привязаны к правилу, а не к строке в базе.

export type CheckKind = 'bad' | 'warn' | 'ok';

export type CheckResult = {
    kind: CheckKind;
    /** короткая пометка у поля */
    short: string;
    /** что Тамара скажет в пузыре */
    say: string;
    /** на чём основано — раскрывается по «почему так» */
    why: string;
};

/** Причины, лежащие вне организации: их владелец уладить не может. */
const EXTERNAL =
    /поставщи|кризис|рынок|рынк|погод|налогов|конкурент|государств|курс валют|санкц|сезон|экономик|власт|банк отказ|клиенты не хотят|люди сейчас/i;

/** Обобщённые названия ресурсов: через месяц по ним нельзя действовать. */
const GENERIC =
    /^(деньги|финансы|сотрудники|персонал|люди|время|оборудование|специалист|специалисты|реклама|клиенты|станок|инструкция|система|обучение|мотивация)[\s.,!]*$/i;

/** Ниже этого «почему» — ярлык, а не причина. */
const MIN_WHY = 30;

/** Ниже этого ситуация — заголовок, а не развёрнутый минус. */
const MIN_SITUATION = 25;

export function checkWhy(input: string): CheckResult | null {
    const text = (input || '').trim();
    if (!text) return null;

    if (EXTERNAL.test(text)) {
        return {
            kind: 'bad',
            short: 'вне организации',
            say: 'Причина, которую ты написал, лежит вне организации. Уладить её ты не можешь, и стратегия на ней встанет. Что внутри компании допускает такое положение — чего у нас нет, чего мы не делаем?',
            why: 'Глава «Почему?»: причина неверна, если лежит вне организации, требует непосильных ресурсов или не даёт облегчения.',
        };
    }
    if (text.length < MIN_WHY) {
        return {
            kind: 'warn',
            short: 'слишком коротко',
            say: 'Слишком коротко — это ярлык, а не причина. Опиши, что именно произошло или чего нет, так, чтобы стало видно, что чинить.',
            why: 'Причина должна открывать дверь к улаживанию. Проверь себя: «теперь-то я точно решу проблему»?',
        };
    }
    return {
        kind: 'ok',
        short: 'причина принята',
        say: 'Причина внутри организации и достаточно конкретна. Осталось проверить два оставшихся критерия — посильна ли она по ресурсам и даёт ли облегчение.',
        why: 'Три критерия верной причины: внутри организации; устранима имеющимися ресурсами; вызывает облегчение.',
    };
}

export function checkSituation(input: string): CheckResult | null {
    const text = (input || '').trim();
    if (!text) return null;

    if (text.length < MIN_SITUATION) {
        return {
            kind: 'warn',
            short: 'это заголовок',
            say: 'Ситуация — это развёрнутый минус, а не заголовок. Допиши, что из-за этого происходит и кому от этого дискомфорт.',
            why: 'Ситуация — самое большое отклонение от образцового положения дел, описанное так, чтобы был виден ущерб.',
        };
    }
    return {
        kind: 'ok',
        short: 'ситуация принята',
        say: 'Ситуация сформулирована. Теперь — почему она возникла.',
        why: 'Не берись улаживать, пока не найдено «почему»: уладишь симптом, а не причину.',
    };
}

export function checkResourceName(input: string): CheckResult | null {
    const text = (input || '').trim();
    if (!text) return null;

    if (GENERIC.test(text) || text.split(/\s+/).length <= 1) {
        return {
            kind: 'bad',
            short: 'обобщённо',
            say: `«${text}» — слишком обобщённо. Сколько именно? Обученных чему? Через месяц ты будешь вспоминать, что имел в виду, вместо того чтобы действовать.`,
            why: 'Не «деньги», а «100 тыс. руб. на новую упаковку». Не «сотрудники», а «сотрудники, обученные тому, как доставлять груз».',
        };
    }
    return null;
}

/** Краткосрочная цель состоит из двух полюсов, и оба обязательны. */
export function checkGoal(goalFix: string, goalGrow: string): CheckResult | null {
    const fix = (goalFix || '').trim();
    const grow = (goalGrow || '').trim();
    if (!fix && !grow) return null;

    if (!grow) {
        return {
            kind: 'bad',
            short: 'нет позитивной части',
            say: 'Позитивной части нет. Если всё время только улаживать, компания будет вечно чинить себя и никуда не придёт. Возьми кусок из цели компании и положи сюда.',
            why: 'Краткосрочная цель состоит из двух полюсов: улаживание ситуации и продвижение к долгосрочной цели.',
        };
    }
    if (!fix) {
        return {
            kind: 'warn',
            short: 'нет улаживания',
            say: 'Нет части про улаживание. Ты нашёл ситуацию — цель должна её закрывать, иначе разбор был напрасным.',
            why: 'Правильная краткосрочная цель учитывает текущую ситуацию и её «почему».',
        };
    }
    return {
        kind: 'ok',
        short: 'обе части на месте',
        say: 'Обе части на месте. Дальше — карта ресурсов: чего у тебя нет, чтобы к этому прийти.',
        why: 'Стратегия строится не из желаний, а из ресурсов.',
    };
}

// Подсказка области по тексту минуса. Возвращает КОД области из shtab_area, а не
// подпись: подписи живут в базе и здесь их быть не должно.
//
// Сопоставление идёт по началу СЛОВА, а не по подстроке где угодно. Иначе
// короткие приметы ловят чужие слова: «ии» сидит внутри «претензии», «тб» —
// внутри «отбраковка», и юридический минус уезжал в «Внедрение ИИ».
// Аббревиатуры из двух-трёх букв требуют полного совпадения слова.
const AREA_HINTS: ReadonlyArray<readonly [readonly string[], string]> = [
    [
        ['цех', 'станок', 'окраск', 'лазер', 'гибочн', 'производств', 'отгруз', 'рекламац', 'деталь', 'сварк', 'покрас', 'тб'],
        'production',
    ],
    [['оплат', 'счёт', 'счет', 'прибыл', 'бюджет', 'касс', 'резерв', 'дебитор', 'кредитор', 'деньг'], 'finance'],
    [['менеджер', 'скрипт', 'конверси', 'продаж', 'чек', 'допродаж'], 'sales'],
    [['лид', 'реклам', 'сайт', 'трафик', 'заявк', 'маркетинг', 'seo'], 'marketing'],
    [['бот', 'ии', 'нейрос', 'агент', 'автоматизац'], 'ai'],
    [['сотрудник', 'штат', 'отпуск', 'найм', 'кадр', 'увольн'], 'hr'],
    [['закуп', 'склад', 'комплектующ', 'поставк', 'снабжен'], 'procurement'],
    [['кд', 'конструктор', 'чертёж', 'чертеж', 'документац'], 'engineering'],
    [['договор', 'претенз', 'суд', 'юрист'], 'legal'],
    [['бухгалт', 'ндс', 'первичк'], 'accounting'],
];

/** Короче этого примета обязана совпасть со словом целиком. */
const EXACT_MATCH_LENGTH = 3;

/** Область по умолчанию, когда текст ни на что не похож. */
export const FALLBACK_AREA = 'management';

export function guessArea(input: string): string {
    const words = (input || '')
        .toLowerCase()
        .split(/[^0-9a-zа-яё]+/)
        .filter(Boolean);
    if (words.length === 0) return FALLBACK_AREA;

    for (const [stems, code] of AREA_HINTS) {
        for (const stem of stems) {
            const hit =
                stem.length <= EXACT_MATCH_LENGTH
                    ? words.some((w) => w === stem)
                    : words.some((w) => w.startsWith(stem));
            if (hit) return code;
        }
    }
    return FALLBACK_AREA;
}
