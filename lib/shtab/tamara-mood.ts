/**
 * Какой ролик живой Тамары включить на ответ.
 *
 * Разбирается реплика владельца, а не ответ Тамары: приветствие и комплимент
 * узнаются по тому, что ей сказали, — сама она на «ты прелесть» отвечает
 * «Спасибо. Приятно. Но я не отвлекаюсь» и дальше по делу, и по её тексту
 * комплимент не опознать.
 *
 * Правило намеренно простое — по словам, без вызова модели: ролик должен
 * включиться сразу вместе с ответом, а не ещё через секунду. Промах здесь
 * дешёвый: вместо улыбки она сделает деловой жест.
 *
 * Слова взяты из настоящей переписки владельца с Тамарой (сентябрь 2026).
 */

export type Mood = 'greet' | 'pleased' | 'explain' | 'twirl';

const GREETING = /^\s*(привет|здравствуй|доброе утро|добрый день|добрый вечер|доброй ночи|хай|салют)/i;

// Ласковые обращения и похвала — то, чем владелец начинает или заканчивает
// реплику: «Тамара, красавица…», «ты прелесть», «Слушай отлично умница».
const COMPLIMENT =
    /(красавиц|прелест|умниц|умничк|солнце|солнышк|сладк|милая|дорогая|отлично выглядишь|хорошо выглядишь|ты такая|ты лучшая|спасибо|благодарю|молодец)/i;

// Про одежду или просьба покрутиться — она поворачивается на месте и
// показывает наряд. Слова без пробела перед ними: «Красивое платье!», «покажи
// наряд». Только в короткой реплике: в поручении «костюм» — это товар.
const OUTFIT =
    /(покрутись|покружись|крутанись|повернись|покажись|наряд|платье|платьиц|костюм|юбк|блузк|прикид|как ты одета|ты сегодня одета)/i;

export function moodOf(question: string): Mood {
    const text = question.trim();
    // Приветствие с делом («привет, посмотри выручку») — всё равно приветствие:
    // она сначала здоровается, потом отвечает.
    if (GREETING.test(text)) return 'greet';
    if (OUTFIT.test(text) && text.length <= 80) return 'twirl';
    // Короткая реплика с лаской — это комплимент. Длинная с «солнце» в начале —
    // это поручение, сказанное ласково: ответ там по делу, а не «спасибо».
    if (COMPLIMENT.test(text) && text.length <= 80) return 'pleased';
    return 'explain';
}
