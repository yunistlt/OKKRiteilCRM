import { TASK_KINDS, tasksOfKind } from '@/lib/shtab/programs';
import type { ProgramDraft, ProgramTask, TaskKind } from '@/lib/shtab/programs';

// Проверки программы — правилами, а не моделью.
//
// Устроено так же, как lib/shtab/checks.ts, и по той же причине: правила из
// методички детерминированы и должны срабатывать одинаково всегда — и на
// программе, которую написала Тамара, и на той, которую написал владелец сам.
// Отдать их модели значило бы менять надёжную проверку на вероятностную.
//
// Самая важная проверка здесь — на производственные задачи. В главе 39 это
// разобрано на примере: рекламная кампания, в которую вложили несколько
// миллионов, была выполнена по всем шагам, все отчитались, а дохода не прибавилось.
// Пропущен был один пункт — числа, к которым программа должна прийти.

export type ProgramProblemKind = 'bad' | 'warn';

export type ProgramProblem = {
    kind: ProgramProblemKind;
    /** Куда смотреть: тип задач или 'main' / 'manager'. */
    at: TaskKind | 'main' | 'manager';
    /** Короткая пометка у поля. */
    short: string;
    /** Что Тамара скажет. */
    say: string;
    /** На чём основано. */
    why: string;
};

const MIN_RABOCHIE = 3;
const MAX_RABOCHIE = 25;
const MIN_MAIN_TASK = 25;

/**
 * Похоже ли слово на инфинитив.
 *
 * Главная задача — это результат («Покраска пропускает такт»), а не действие
 * («Расшить покраску»). Отличить их по первому слову можно только приблизительно,
 * поэтому такая находка идёт предупреждением, а не браком.
 *
 * Голого окончания «-ть» мало: на него кончается целый пласт отглагольных
 * существительных — «ответственность», «область», «часть», — и по нему проверка
 * ругалась бы на совершенно правильные формулировки. Поэтому такие окончания
 * исключены отдельно.
 */
const NOUN_TAIL = /(ость|есть|асть|исть|усть|ысть)$/i;
const INFINITIVE_TAIL = /(ть|ти|чь)$/i;

export function looksLikeInfinitive(word: string): boolean {
    const w = word.trim().toLowerCase().replace(/[^а-яё]/g, '');
    if (w.length < 4) return false;
    if (NOUN_TAIL.test(w)) return false;
    return INFINITIVE_TAIL.test(w);
}

/**
 * Есть ли в тексте число — цифрой или словом («сто процентов», «на каждом участке»).
 *
 * Границы слова заданы просмотром вперёд и назад, а не «\b». В JavaScript «\b»
 * определена через латинский \w, и рядом с кириллицей не работает вовсе: «\bсто»
 * не находит «сто» даже в начале строки. Без границ же «сто» нашлось бы внутри
 * «стоимости» и «простоя» — а это как раз слова из производственных задач.
 */
const CYR_EDGE_L = '(?<![а-яёa-z])';
const CYR_EDGE_R = '(?![а-яёa-z])';
const NUMBER_WORD = new RegExp(`${CYR_EDGE_L}(сто|все|каждом|каждый|каждого|ни одного|ноль)${CYR_EDGE_R}`, 'i');

function hasNumber(text: string): boolean {
    return /\d/.test(text) || NUMBER_WORD.test(text);
}

function checkMainTask(draft: ProgramDraft): ProgramProblem[] {
    const out: ProgramProblem[] = [];
    const main = (draft.mainTask || '').trim();

    if (!main) {
        out.push({
            kind: 'bad',
            at: 'main',
            short: 'нет главной задачи',
            say: 'У программы нет главной задачи. Пока не написано, какой результат должен получиться, остальные шаги не к чему привязать.',
            why: 'Глава 38: главная задача — это ответ на вопрос «какой результат получится после выполнения этой части стратегии».',
        });
        return out;
    }

    if (main.length < MIN_MAIN_TASK) {
        out.push({
            kind: 'warn',
            at: 'main',
            short: 'слишком коротко',
            say: 'Главная задача слишком короткая, чтобы по ней можно было сказать «сделано» или «не сделано». Опиши результат так, чтобы его нельзя было понять двояко.',
            why: 'По главной задаче потом принимается решение, выполнена программа или нет.',
        });
    }

    if (looksLikeInfinitive(main.split(/\s+/)[0] ?? '')) {
        out.push({
            kind: 'warn',
            at: 'main',
            short: 'это действие, а не результат',
            say: 'Главная задача написана действием: «расшить», «наладить», «обеспечить». Действие можно выполнить и ничего не изменить. Напиши результат: как выглядит участок, когда программа сделана.',
            why: 'Глава 38: главная задача — результат выполнения части стратегии, а не перечень того, что будет сделано.',
        });
    }

    return out;
}

/**
 * Сколько в записи названо должностей.
 *
 * Считаются не вхождения слова, а сегменты, которые с должности НАЧИНАЮТСЯ. Обе
 * более простые проверки дают ложные срабатывания на настоящих записях:
 *
 *   «есть союз „и“ или запятая» → «Начальник цеха по качеству и технологическому
 *   процессу» это одна должность, «Сотрудник, отвечающий за приём» один человек;
 *
 *   «сколько раз встретился стем должности» → в том же «технологическому»
 *   находится «технолог», и один человек превращается в двух.
 *
 * Отдельно про «\b»: в JavaScript эта граница определена через латинский \w и с
 * кириллицей не работает — «\bначальник» не находит «Начальник» даже в начале
 * строки. Поэтому границы здесь заданы разбором на сегменты, а не регуляркой.
 */
// Слово целиком, а не стем: «технолог» иначе находится в «технологическому»,
// и «Начальник цеха по качеству и технологическому процессу» — одна должность —
// превращается в двух руководителей.
const ROLE_HEAD =
    /^(начальник|директор|мастер|сотрудник|руководитель|инженер|технолог|владелец|бригадир|менеджер|прораб)(?![а-яё])/i;

const SEGMENT_SPLIT = /[,;/+]|\s+и\s+|\s+или\s+/i;

/** Две фамилии подряд через запятую или косую: «Иванов, Петров». */
const TWO_NAMES = /[А-ЯЁ][а-яё]+\s*[,;/]\s*[А-ЯЁ][а-яё]+/;

export function countManagers(name: string): number {
    const heads = name
        .split(SEGMENT_SPLIT)
        .map((part) => part.trim())
        .filter((part) => ROLE_HEAD.test(part)).length;

    if (heads > 0) return heads;
    // Должностей не названо вовсе — считаем по фамилиям.
    return TWO_NAMES.test(name) ? 2 : 1;
}

function checkManager(draft: ProgramDraft): ProgramProblem[] {
    const name = (draft.managerName || '').trim();

    if (!name) {
        return [{
            kind: 'bad',
            at: 'manager',
            short: 'нет руководителя',
            say: 'У программы нет руководителя. Назначь одного человека — не отдел и не двоих.',
            why: 'Глава 38: назначенный руководитель — обязательный компонент программы наравне с главной задачей и показателями.',
        }];
    }

    if (countManagers(name) > 1) {
        return [{
            kind: 'bad',
            at: 'manager',
            short: 'руководителей больше одного',
            say: `В руководителях указано несколько: «${name}». У программы с двумя ответственными ответственных ноль — каждый уверен, что разберётся второй, и оба правы. Выбери одного, второй помогает.`,
            why: 'Обязательный компонент программы — один назначенный руководитель.',
        }];
    }

    return [];
}

function checkProizvodstvennye(tasks: readonly ProgramTask[]): ProgramProblem[] {
    const out: ProgramProblem[] = [];
    const prod = tasksOfKind(tasks, 'proizvodstvennaya');

    if (prod.length === 0) {
        out.push({
            kind: 'bad',
            at: 'proizvodstvennaya',
            short: 'нет производственных задач',
            say: 'В программе нет производственных задач — чисел, к которым она должна прийти. Без них программу выполнят по шагам, все отчитаются, а результата не будет. Напиши, что должно измениться в цифрах.',
            why: 'Глава 39: рекламная кампания на несколько миллионов была выполнена по всем шагам, и доход не вырос. Пропущен был ровно этот пункт.',
        });
        return out;
    }

    for (const t of prod) {
        const target = (t.targetValue || '').trim();
        const source = (t.sourceNote || '').trim();

        if (!target && !source) {
            out.push({
                kind: 'bad',
                at: 'proizvodstvennaya',
                short: 'число не названо и неоткуда взять',
                say: `«${t.text}» — числа нет, и не сказано, каким замером оно закрывается. Пропуск допустим, но только с указанием источника: иначе задача останется пожеланием.`,
                why: 'Пропуск с названным замером — это план работы. Пропуск без него — это отсутствие производственной задачи.',
            });
            continue;
        }

        if (target && !hasNumber(target) && !hasNumber(t.text)) {
            out.push({
                kind: 'warn',
                at: 'proizvodstvennaya',
                short: 'значение без числа',
                say: `«${t.text}» — в целевом значении нет числа. «Улучшить», «повысить», «навести порядок» проверить нельзя.`,
                why: 'Производственная задача измеряется, иначе по ней нельзя сказать, выполнена программа или нет.',
            });
        }
    }

    return out;
}

function checkRabochie(tasks: readonly ProgramTask[]): ProgramProblem[] {
    const rab = tasksOfKind(tasks, 'rabochaya');

    if (rab.length < MIN_RABOCHIE) {
        return [{
            kind: 'bad',
            at: 'rabochaya',
            short: 'шагов почти нет',
            say: `Рабочих задач ${rab.length}. Это не программа, а намерение: «сделайте вот это» слишком обобщённо, чтобы кто-то мог взять и выполнить.`,
            why: 'Глава 38: шаги считаются обратным отсчётом от результата, пока не дойдёшь до того, что можно начать делать завтра.',
        }];
    }

    if (rab.length > MAX_RABOCHIE) {
        return [{
            kind: 'warn',
            at: 'rabochaya',
            short: 'шагов слишком много',
            say: `Рабочих задач ${rab.length} — похоже, в один блок попало несколько программ. Проверь нарезку: скорее всего, блок надо разделить.`,
            why: 'Одна программа — один результат. Если результатов несколько, программ тоже несколько.',
        }];
    }

    return [];
}

function checkVital(tasks: readonly ProgramTask[]): ProgramProblem[] {
    if (tasksOfKind(tasks, 'zhiznenno_vazhnaya').length > 0) return [];

    return [{
        kind: 'warn',
        at: 'zhiznenno_vazhnaya',
        short: 'нет жизненно важных задач',
        say: 'Не названо ни одного условия, нарушение которого убивает программу. Подумай: что нельзя делать в обход, даже если очень захочется сэкономить время?',
        why: 'Глава 40: жизненно важные задачи формулируются не действиями, а правилами; их нарушение означает смерть всей программы.',
    }];
}

function checkPervoocherednye(tasks: readonly ProgramTask[]): ProgramProblem[] {
    if (tasksOfKind(tasks, 'pervoocherednaya').length > 0) return [];

    return [{
        kind: 'warn',
        at: 'pervoocherednaya',
        short: 'нет подготовки',
        say: 'Нет первоочередных задач. Как минимум: назначить руководителя, дать ему прочитать программу и понять её, взять ответственность за результат.',
        why: 'Глава 40: программа, сделанная без понимания, выполняется на отписку.',
    }];
}

/**
 * Все проблемы программы. Пустой список — программа по форме в порядке; это не
 * означает, что она хорошая по существу, — существо оценивает владелец.
 */
export function checkProgram(draft: ProgramDraft): ProgramProblem[] {
    const tasks = draft.tasks ?? [];

    const problems = [
        ...checkMainTask(draft),
        ...checkManager(draft),
        ...checkPervoocherednye(tasks),
        ...checkVital(tasks),
        ...checkRabochie(tasks),
        ...checkProizvodstvennye(tasks),
    ];

    const unknown = tasks.filter((t) => !TASK_KINDS.includes(t.kind));
    if (unknown.length > 0) {
        problems.push({
            kind: 'bad',
            at: 'rabochaya',
            short: 'неизвестный тип задачи',
            say: `Тип задачи не из методички: ${Array.from(new Set(unknown.map((t) => String(t.kind)))).join(', ')}.`,
            why: 'Типов задач пять, и справочник закрыт: первоочередные, жизненно важные, рабочие, производственные, условные.',
        });
    }

    return problems;
}

/** Есть ли брак — то, что по методичке делает программу неработающей. */
export function hasBlockingProblems(problems: readonly ProgramProblem[]): boolean {
    return problems.some((p) => p.kind === 'bad');
}
