/**
 * Поиск по словам: находятся все слова запроса, в любом порядке, без учёта
 * регистра.
 *
 * Андрей 14.10.2026: «паспорт SL» не находил
 * «Паспорт_Сушильный_стеллаж_SL1_Вираж_16», потому что искали фразу целиком.
 * Человек же набирает приметы по памяти — тип документа и кусок модели, — а в
 * названии между ними ещё полстроки.
 *
 * Поэтому каждое слово ищется отдельным вхождением, и найтись должны все.
 * Знаки между словами роли не играют: в названиях ЗМК там то пробел, то дефис,
 * то подчёркивание.
 */

/** Сколько слов берём в расчёт: дальше человек уже не уточняет, а шумит. */
const MAX_WORDS = 6;

/**
 * Запятые и скобки ломают фильтр PostgREST, а «%» и «_» в LIKE — подстановочные
 * знаки: в названиях изделий они встречаются сплошь, и без экранирования запрос
 * молча означает не то, что набрал человек.
 */
function safeWord(word: string): string {
    return word.replace(/[,()]/g, ' ').replace(/[%_]/g, (ch) => `\\${ch}`).trim();
}

export function searchWords(query: string): string[] {
    return String(query ?? '')
        .trim()
        .split(/\s+/)
        .map(safeWord)
        .filter(Boolean)
        .slice(0, MAX_WORDS);
}

/** «колонка похожа на все слова» — одним условием PostgREST. */
export function allWordsIlike(column: string, words: string[]): string {
    return words.map((word) => `${column}.ilike.%${word}%`).join(',');
}

/**
 * «подходит одна колонка ИЛИ другая», и в каждой — все слова.
 *
 * Собирается строкой, а не цепочкой .ilike(): цепочка даёт только И, а здесь
 * нужно И внутри колонки и ИЛИ между колонками.
 */
export function anyColumnAllWords(columns: string[], words: string[]): string {
    return columns.map((column) => `and(${allWordsIlike(column, words)})`).join(',');
}
