/**
 * Цвет текста на цветной плашке статуса или группы.
 *
 * Цвет группы человек выбирает сам, и тёмный он выбирает наравне со светлым:
 * на доске статусов группа «Технические» оказалась почти чёрной, а названия
 * статусов на ней остались серыми — их не было видно совсем (замечание
 * владельца 05.10.2026).
 *
 * Поэтому цвет текста не задаём, а считаем от яркости фона. Порог высокий:
 * на фирменном оранжевом белый текст читается лучше и выглядит спокойнее —
 * так же, как в RetailCRM.
 */
export function textOnColor(hex: string | null | undefined): string {
    const match = /^#?([0-9a-f]{6})$/i.exec(String(hex ?? '').trim());
    if (!match) return '#111827';

    const value = parseInt(match[1], 16);
    const luminance = (0.299 * ((value >> 16) & 255) + 0.587 * ((value >> 8) & 255) + 0.114 * (value & 255)) / 255;
    return luminance > 0.72 ? '#111827' : '#ffffff';
}

/** Приглушённый текст (норматив, название группы) на том же фоне. */
export function mutedOnColor(hex: string | null | undefined): string {
    return textOnColor(hex) === '#ffffff' ? 'rgba(255,255,255,0.75)' : '#6b7280';
}
