export const SPEC_BY_KEY = new Map(SETTINGS_SCHEMA.map((s) => [s.key, s]));

/** Настройка, которой нет в схеме, показывается как есть — прятать нельзя. */
export function specFor(key: string): SettingSpec {
    return (
        SPEC_BY_KEY.get(key) ?? {
            key,
            title: key,
            hint: 'Настройка появилась позже этого экрана — название ещё не задано. Влияет на работу бота, поэтому показана как есть.',
            kind: 'text',
            group: 'Прочее',
        }
    );
}
