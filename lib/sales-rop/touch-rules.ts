/**
 * Что считается выполнением задачи дня.
 *
 * Касание по заказу — любой след работы: звонок, письмо, смена статуса,
 * комментарий, правка, перенос даты следующего контакта. Но выполнением
 * задачи это не равно.
 *
 * Перенос даты задачу не закрывает (закон владельца 28.10.2026). Задача
 * звучит «сегодня по плану звонок клиенту»; сдвинув дату, менеджер её не
 * сделал, а отложил — и, если это засчитывать, клиента можно отодвигать
 * бесконечно, а план будет показывать «отработано». Сам перенос из плана не
 * прячем: он остаётся подписью под задачей, чтобы было видно, что с заказом
 * делали.
 */

/** Касания, которые задачу не закрывают. */
export const TOUCHES_NOT_DONE = ['перенос даты', 'перенос даты без причины'];

/** Закрывает ли такое касание задачу дня. */
export function touchClosesTask(kind: string | null | undefined): boolean {
    const touch = String(kind ?? '').trim();
    return Boolean(touch) && !TOUCHES_NOT_DONE.includes(touch);
}

/**
 * Почему задача осталась на сегодня, хотя с заказом работали.
 *
 * Ирина Гордеева 29.10.2026 (доработки №63 и №64): «запрос обработан, всё равно
 * выкидывает на страничку этого заказа, не меняет на следующую задачу». По
 * заказу 52790 она перенесла дату контакта и написала причину, но звонка не
 * было — задача правомерно осталась открытой. Экран об этом молчал и выглядел
 * сломанным.
 *
 * Возвращает строку, которую видит менеджер, или null — если задача закрыта
 * либо с заказом сегодня ничего не делали.
 */
export function openTaskNote(kind: string | null | undefined): string | null {
    const touch = String(kind ?? '').trim();
    if (!touch || touchClosesTask(touch)) return null;
    return 'Дату перенесли, а звонка не было — план этим не закрывается, задача остаётся на сегодня.';
}

/** Одна формулировка правила для интерфейса, бота и базы знаний. */
export const TASK_DONE_RULE =
    'Задача считается отработанной, если по заказу сегодня был звонок, письмо, комментарий или смена статуса. '
    + 'Перенос даты следующего контакта задачу не закрывает.';
