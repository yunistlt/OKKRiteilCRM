/**
 * Обращение в письме: по имени и отчеству.
 *
 * Просьба менеджеров 08.10.2026 — в RetailCRM так и было: «Добрый день,
 * Артём Иванович». По фамилии или по полному ФИО обращаться нельзя: «Добрый
 * день, Иванов Артём Иванович» выглядит повесткой.
 *
 * Отчество есть не всегда — заполнено у 5 068 заказов из 30 208 на 08.10.2026,
 * поэтому обращение собирается с запасными вариантами, а не падает в пустоту.
 */
export function buildGreeting(person: {
    firstName?: string | null;
    patronymic?: string | null;
}): string {
    const first = String(person.firstName ?? '').trim();
    const middle = String(person.patronymic ?? '').trim();

    if (first && middle) return `Добрый день, ${first} ${middle}!`;

    /**
     * Имя одним словом — обращаемся по нему. Несколько слов в поле «Имя»
     * означает, что туда записали всё ФИО сразу: у своих заказов встречается
     * «Сигачев Павел». Разобрать, где здесь имя, а где фамилия, нельзя —
     * порядок у всех разный. Угадывать не будем: обратимся без имени, это
     * лучше, чем назвать человека фамилией.
     */
    if (first && !/\s/.test(first)) return `Добрый день, ${first}!`;
    // Имени нет — обращаемся без него: выдумывать «уважаемый клиент» не нужно.
    return 'Добрый день!';
}
