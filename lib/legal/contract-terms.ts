/** Условия по коду. Неизвестный код — null: текст тогда пишет менеджер. */
export function standardTerm(code: string | null | undefined): ContractTerm | null {
    if (!code) return null;
    return STANDARD_CONTRACT_TERMS.find((t) => t.code === code) ?? null;
}
