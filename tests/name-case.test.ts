/**
 * Падежи ФИО в договоре.
 *
 * В преамбуле нужен родительный («в лице Директора Шуняевой Фаузили
 * Рифовны»), в строке подписи — именительный («/ Шуняева Фаузиля Рифовна /»).
 * Менеджеры хранили в карточке родительный, и подпись выходила с чужим
 * падежом (12.10.2026).
 */
import { describe, it, expect } from 'vitest';
import { titleToGenitive, toGenitive } from '@/lib/legal/name-case';

describe('родительный падеж ФИО', () => {
    it('женщина: фамилия на -ева', () => {
        expect(toGenitive('Шуняева Фаузиля Рифовна')).toBe('Шуняевой Фаузили Рифовны');
    });

    it('мужчина: фамилия на -ов', () => {
        expect(toGenitive('Теренков Андрей Анатольевич')).toBe('Теренкова Андрея Анатольевича');
    });

    it('женщина: имя на -ия', () => {
        expect(toGenitive('Иванова Мария Сергеевна')).toBe('Ивановой Марии Сергеевны');
    });

    it('мужчина: фамилия на согласную', () => {
        expect(toGenitive('Левчук Игорь Петрович')).toBe('Левчук Игоря Петровича');
    });

    it('несклоняемую фамилию не трогаем', () => {
        expect(toGenitive('Шевченко Ольга Ивановна')).toBe('Шевченко Ольги Ивановны');
    });

    it('уже родительный падеж проходит без порчи', () => {
        expect(toGenitive('Шуняевой Фаузили Рифовны')).toBe('Шуняевой Фаузили Рифовны');
    });

    it('пустое и короткое не ломают договор', () => {
        expect(toGenitive('')).toBe('');
        expect(toGenitive('Петров')).toBe('Петрова');
    });
});

describe('должность в родительном падеже', () => {
    it('директор → директора', () => {
        expect(titleToGenitive('Директор')).toBe('Директора');
    });

    it('генеральный директор → генерального директора', () => {
        expect(titleToGenitive('Генеральный директор')).toBe('Генерального директора');
    });

    it('уже родительный не трогаем', () => {
        expect(titleToGenitive('Генерального директора')).toBe('Генерального директора');
    });

    it('пусто — пусто, договор не ломается', () => {
        expect(titleToGenitive(null)).toBe('');
    });
});
