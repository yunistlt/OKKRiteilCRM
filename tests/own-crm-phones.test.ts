import { describe, it, expect } from 'vitest';
import { phoneKey, uniquePhones } from '@/lib/own-crm/phones';

/** Заказ 49583: один рабочий номер в трёх записях и мобильный, который не был виден. */
describe('телефоны заказа', () => {
    it('один номер в разных записях — одна строка', () => {
        expect(uniquePhones([
            '+7 (812) 670-23-03',
            '+78126702303',
            '8126702303',
            '+7931-297-20-26',
            '+7-931-297-20-26',
        ])).toEqual(['+7 (812) 670-23-03', '+7931-297-20-26']);
    });

    it('мобильный виден вторым, а не теряется в хвосте', () => {
        const [primary, secondary, third] = uniquePhones([
            '+7 (812) 670-23-03',
            '+7931-297-20-26',
            '+78126702303',
            '+7 (812) 670-23-03',
        ]);
        expect(primary).toBe('+7 (812) 670-23-03');
        expect(secondary).toBe('+7931-297-20-26');
        expect(third).toBeUndefined();
    });

    it('пустое и обрывки номерами не считаются', () => {
        expect(uniquePhones([null, undefined, '', '  ', '123', 'доб. 105'])).toEqual([]);
    });

    it('номер узнаётся по последним десяти цифрам', () => {
        expect(phoneKey('+7 (931) 297-20-26')).toBe('9312972026');
        expect(phoneKey('8 931 297 20 26')).toBe('9312972026');
    });
});
