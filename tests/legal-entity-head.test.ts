import { describe, it, expect } from 'vitest';
import { humanTitle, sealPlaceFrom } from '@/lib/own-crm/legal-entity-head';

/**
 * Должность руководителя приходит из ЕГРЮЛ капсом, а в счёте капса быть не
 * должно (закон «интерфейс — человеческий язык»). Аббревиатуры при этом
 * остаются аббревиатурами.
 */
describe('должность подписанта человеческим языком', () => {
    it('генеральный директор', () => {
        expect(humanTitle('ГЕНЕРАЛЬНЫЙ ДИРЕКТОР')).toBe('Генеральный директор');
    });

    it('аббревиатура после дефиса остаётся заглавной', () => {
        expect(humanTitle('УПРАВЛЯЮЩИЙ-ИП')).toBe('Управляющий-ИП');
    });

    it('простая должность', () => {
        expect(humanTitle('ДИРЕКТОР')).toBe('Директор');
    });

    it('пусто остаётся пустым', () => {
        expect(humanTitle(null)).toBeNull();
        expect(humanTitle('   ')).toBeNull();
    });
});

/**
 * Место на печати — человеческим языком: в ЕГРЮЛ оно приходит сокращениями
 * («Респ Татарстан», «Самарская обл», «г Тольятти»), а на оттиске так не
 * пишут (образцы печатей ЗМК, ПОБТ и ЗВТО от владельца 02.10.2026).
 */
describe('место на печати', () => {
    it('область и город разворачиваются', () => {
        expect(sealPlaceFrom('Самарская обл', 'г Тольятти')).toBe('Россия, Самарская область, город Тольятти');
    });

    it('республика', () => {
        expect(sealPlaceFrom('Респ Татарстан', 'г Елабуга')).toBe('Россия, Республика Татарстан, город Елабуга');
    });

    it('город совпал с регионом — не повторяем', () => {
        expect(sealPlaceFrom('г Москва', 'Москва')).toBe('Россия, город Москва');
    });

    it('без региона и города — только страна не пишем', () => {
        expect(sealPlaceFrom(null, null)).toBeNull();
    });
});
