/**
 * Поиск по каталогу: буквы-двойники и числа.
 *
 * Доработки 41–43 (Ирина Гордеева, 22.10.2026):
 *  - «Не показывает для добавления в корзину шкаф ШСО-02» — на витрине он
 *    записан латинской «O»: «Шкаф сушильный ШСO 02». Таких названий 67 из
 *    8 291, и глазом подмену не видно.
 *  - «не показывает, если набрать суш стеллаж на 20 пар» — «20» искалось
 *    куском любого числа и находилось в габаритах «2200х1250х515»: выдавались
 *    стеллажи на 40, 48, 72 и 90 пар, и система молчала, что двадцати среди
 *    них нет.
 */
import { describe, expect, it } from 'vitest';
import { confusableLike, foldLookalikes, looseLike, normalizeForMatch } from '@/lib/shtab/lvz';

describe('буквы-двойники в каталоге', () => {
    it('сводит латинские двойники к русским буквам', () => {
        // «ШСO 02» с витрины и «ШСО 02» от менеджера должны стать одним и тем же.
        expect(normalizeForMatch('Шкаф сушильный ШСO 02')).toBe(normalizeForMatch('Шкаф сушильный ШСО 02'));
        expect(normalizeForMatch('ЕRGO 181')).toBe(normalizeForMatch('ERGO 181'));
        expect(normalizeForMatch('Cушильный шкаф')).toBe(normalizeForMatch('Сушильный шкаф'));
    });

    it('не трогает буквы без двойников', () => {
        // «SL1» и «СЛ1» — разные обозначения, сводить их нельзя.
        expect(normalizeForMatch('SL1 Вираж')).not.toBe(normalizeForMatch('СЛ1 Вираж'));
        expect(foldLookalikes('Шкаф')).toBe('Шкаф');
    });

    it('в образце для базы двойники становятся подстановкой', () => {
        // Точный образец ищет ровно то, что набрано; терпимый — с «_» на месте
        // букв, которые бывают написаны обоими алфавитами.
        expect(looseLike('ШСО-02')).toBe('ШСО%02');
        // «С» и «О» бывают и латинскими — на их месте подойдёт любой знак.
        expect(confusableLike('ШСО-02')).toBe('Ш__%02');
        // Цифры подстановкой не становятся: иначе «02» нашло бы что угодно.
        expect(confusableLike('02')).toBe('02');
    });
});
