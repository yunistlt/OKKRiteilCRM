import { describe, it, expect } from 'vitest';
import { isElectronicTenderInvite } from '@/lib/email/classify';

/**
 * Гейт электронных торгов. Цена ошибки несимметрична: лишний заказ по торгам — мусор в CRM,
 * а пропущенный внутренний тендер — потерянная заявка. Поэтому «не заявка» ставим только при
 * явном признаке площадки. Случаи взяты из боевых писем (заказы 54207 / 54164 / 54046).
 */
describe('isElectronicTenderInvite', () => {
    it('ловит приглашение на площадку — участие через портал закупок (заказ 54207 завёлся зря)', () => {
        expect(isElectronicTenderInvite({
            subject: 'Приглашение к участию в закупке',
            body: 'Приглашаем принять участие в закупке. Для участия необходимо зарегистрироваться на площадке и подать заявку в личном кабинете. Письмо создано автоматически.',
            fromName: 'Портал закупок Аквилон',
            fromEmail: 'noreply@zakupki.example.ru',
        })).toBe(true);
    });

    it('ловит торги по 44-ФЗ на ЭТП', () => {
        expect(isElectronicTenderInvite({
            subject: 'Извещение о проведении электронного аукциона',
            body: 'Электронный аукцион по 44-ФЗ проводится на электронной торговой площадке roseltorg. Требуется аккредитация на площадке.',
        })).toBe(true);
    });

    it('НЕ трогает внутренний тендер: ТКП просят на e-mail (СИСЭнергострой, заказ 54164)', () => {
        expect(isElectronicTenderInvite({
            subject: 'Запрос предложений на изготовление стеллажей',
            body: 'Данная закупка не является торгами. Просим направить ТКП на электронную почту tender@sisenergo.ru. Техническое задание во вложении.',
        })).toBe(false);
    });

    it('НЕ трогает закупочную сессию с ответом письмом (Дорогобуж/Акрон, заказ 54046)', () => {
        expect(isElectronicTenderInvite({
            subject: 'Закупочная сессия — шкафы металлические',
            body: 'Приглашаем к участию в закупочной сессии. Коммерческое предложение просим направить письмом на адрес zakupki@dorogobuzh.ru до 15.08.',
        })).toBe(false);
    });

    it('НЕ трогает обычный запрос цены — там нет закупочной процедуры', () => {
        expect(isElectronicTenderInvite({
            subject: 'Стеллажи',
            body: 'Здравствуйте! Нужен расчёт на 20 шт стеллажей 2000х1000. Пришлите КП и сроки.',
        })).toBe(false);
    });
});
