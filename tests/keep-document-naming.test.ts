import { describe, expect, it } from 'vitest';

/**
 * Имя второго за день документа получает время, чтобы в списке файлов
 * различались два разных КП (Ирина Гордеева 14.10.2026, заказ 48884).
 */
const withTime = (filename: string, time: string) =>
    filename.replace(/(\.[^.]+)?$/, (ext) => ` (${time})${ext || ''}`);

describe('имя повторного документа за день', () => {
    it('время встаёт перед расширением', () => {
        expect(withTime('КП №48884.pdf', '10:22')).toBe('КП №48884 (10:22).pdf');
    });

    it('без расширения — время в конце', () => {
        expect(withTime('КП №48884', '10:22')).toBe('КП №48884 (10:22)');
    });

    it('точка в названии не путает', () => {
        expect(withTime('Счёт от 14.10.pdf', '09:05')).toBe('Счёт от 14.10 (09:05).pdf');
    });
});
