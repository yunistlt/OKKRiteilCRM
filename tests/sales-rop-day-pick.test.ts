/**
 * Какой день разбирает бот-РОП.
 *
 * Крон ходит по будням и брал календарное «вчера»: в понедельник это
 * воскресенье, а пятница не разбиралась никогда (потеряли 06.11.2026 —
 * 112 разговоров). Закрываем тестом, чтобы не вернулось.
 */
import { describe, it, expect } from 'vitest';
import { previousWorkday } from '@/lib/sales-rop/day-review';

/** Полдень в Москве указанной даты. */
const mskNoon = (iso: string) => Date.parse(`${iso}T12:00:00+03:00`);

describe('предыдущий рабочий день', () => {
    it('в понедельник разбираем пятницу', () => {
        expect(previousWorkday(mskNoon('2026-11-09'))).toBe('2026-11-06');
    });

    it('в среду — вторник', () => {
        expect(previousWorkday(mskNoon('2026-11-11'))).toBe('2026-11-10');
    });

    it('выходные пропускаются и с воскресенья', () => {
        expect(previousWorkday(mskNoon('2026-11-08'))).toBe('2026-11-06');
    });

    it('полночь по Москве считается тем же днём', () => {
        expect(previousWorkday(Date.parse('2026-11-09T00:30:00+03:00'))).toBe('2026-11-06');
    });
});
