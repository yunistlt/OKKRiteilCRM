/**
 * Год в письме не должен считаться номером заказа.
 *
 * Жалоба Евгении Матвеевой 19.10.2026: запрос акта сверки ушёл менеджеру
 * вместо бухгалтерии. Причина — «акт сверки за 2026 год» читалось как заказ
 * №2026 (такой заказ есть, отменённый, от 2017 года), а письмо по заказу в
 * отдел не пересылается.
 */
import { describe, expect, it } from 'vitest';
import { looksLikeYearNotOrder } from '@/lib/email/order-tag';

describe('год вместо номера заказа', () => {
    it('ловит живые письма про акты сверки', () => {
        expect(looksLikeYearNotOrder('2026', 'Акт сверки 2026', 'Прошу сделать акт сверки за 2026 год. Спасибо')).toBe(true);
        expect(looksLikeYearNotOrder('2026', 'СРОЧНО!!! Акт сверки за 3 квартал 2026 г. ИП Соколик О. А.', '')).toBe(true);
        expect(looksLikeYearNotOrder('2026', null, 'Просим выслать акт сверки за 3 кв. 2026 г.')).toBe(true);
    });

    it('не трогает настоящие номера заказов', () => {
        expect(looksLikeYearNotOrder('53877', 'Re: по заказу 53877', 'за 2026 год')).toBe(false);
        expect(looksLikeYearNotOrder('900294', 'Заказ 900294', '')).toBe(false);
        // Четырёхзначный номер вне годового диапазона — обычный заказ.
        expect(looksLikeYearNotOrder('5877', 'по заказу 5877 за 2026 год', '')).toBe(false);
    });

    it('год без годового контекста номером не считает только по виду', () => {
        // «заказ 2026» без слов про год — привязка остаётся, решает база.
        expect(looksLikeYearNotOrder('2026', 'Заказ 2026 отгрузка', 'по заказу 2026 вопрос')).toBe(false);
    });
});
