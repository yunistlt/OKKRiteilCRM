import { describe, expect, it } from 'vitest';

/**
 * Разбор темы на номера заказов проверяем отдельно от разметки: важна именно
 * выборка чисел — лишняя ссылка ведёт в никуда и злит сильнее, чем её
 * отсутствие.
 */
const PATTERN = /\[#\d+\/(\d{4,6})\]|(?:заказ[а-яё]*\s*№?\s*)(\d{4,6})|\b(9\d{5})\b/gi;

const numbers = (text: string) =>
    [...text.matchAll(PATTERN)].map((m) => m[1] || m[2] || m[3]).filter(Boolean);

describe('номера заказов в тексте', () => {
    it('берёт номер из служебного тега темы', () => {
        expect(numbers('Re: [#2/54776] Ирина Валерьевна')).toEqual(['54776']);
    });

    it('берёт номер после слова «заказ»', () => {
        expect(numbers('по заказу № 54776')).toEqual(['54776']);
        expect(numbers('Заказ 900056 оплачен')).toEqual(['900056']);
    });

    it('берёт свой номер вида 9xxxxx', () => {
        expect(numbers('оплата по 900042 прошла')).toEqual(['900042']);
    });

    it('не делает ссылок из сумм и дат', () => {
        expect(numbers('сумма 442800 рублей, срок 2026 год')).toEqual([]);
    });
});
