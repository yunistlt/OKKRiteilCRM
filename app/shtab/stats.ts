// Реестр статистик Пульта.
//
// У каждой метрики указано, откуда берётся ряд:
//   'api'         — считается по живым данным, приходит с /api/shtab/stats;
//   'placeholder' — источника пока нет, показываем демонстрационный ряд и
//                   подписываем, откуда числа появятся.
//
// Заглушки оставлены сознательно, а не забыты. Раздел, показывающий
// правдоподобное, но непроверенное число, хуже раздела, который честно говорит
// «данных мало»: на честности счёта стоит вся его конструкция. Подключить
// метрику — это сменить source на 'api' и добавить запрос в маршрут статистик.

export type StatPeriod = 'week' | 'month';
export type StatSource = 'api' | 'placeholder';

export type Stat = {
    /** ключ ряда в ответе /api/shtab/stats */
    key: string;
    name: string;
    unit: string;
    /** откуда берутся числа: живой источник или что должно им стать */
    src: string;
    source: StatSource;
    period: StatPeriod;
    /** демонстрационный ряд — только для source: 'placeholder' */
    sample?: number[];
    /** знаков после запятой */
    dp: number;
};

