'use client';

/**
 * «Очистить фильтр» — одна кнопка на все таблицы.
 *
 * Решение владельца 14.10.2026: где есть отбор, там должен быть и способ снять
 * его целиком, одним нажатием. Записано в золотой стандарт таблиц, §5.
 *
 * Отдельный компонент, а не разметка в каждом реестре, по двум причинам:
 * подпись и вид везде одинаковые (человек узнаёт кнопку, не читая), и правило
 * нельзя случайно забыть — его видно по импорту.
 *
 * Кнопка появляется, только когда есть что снимать: пустая она бессмысленна и
 * лишь занимает место в и без того плотной шапке.
 */
export default function ClearFiltersButton({
    active,
    onClear,
    className = '',
}: {
    /** Отобрано хоть что-то. */
    active: boolean;
    /** Вернуть таблицу к полному списку: снять отбор, поиск и уйти на первую страницу. */
    onClear: () => void;
    className?: string;
}) {
    if (!active) return null;

    return (
        <button
            type="button"
            onClick={onClear}
            title="Снять весь отбор и показать полный список"
            className={`border border-gray-300 bg-white px-3 py-1 text-xs font-semibold text-gray-700 hover:bg-gray-50 ${className}`}
        >
            Очистить фильтр
        </button>
    );
}
