'use client';

/**
 * Календарь и часы открываются щелчком по всему полю, а не только по значку
 * справа.
 *
 * Просьба владельца 05.10.2026 — про дату в карточке заказа; Евгения Матвеева
 * 15.10.2026 — про задачи: «нужно, чтобы в Задачах ячейки Дата и Время
 * активизировались при нажатии на любое место в поле в ячейке». Значок у этих
 * полей шириной в пару миллиметров, попасть в него мышкой трудно.
 *
 * Печатать дату руками по-прежнему можно: поле остаётся обычным полем ввода.
 */
import type { MouseEvent } from 'react';

export function openPickerOnClick(event: MouseEvent<HTMLInputElement>) {
    const el = event.currentTarget as HTMLInputElement & { showPicker?: () => void };
    try {
        el.showPicker?.();
    } catch {
        // Старый браузер — остаётся значок справа, как раньше.
    }
}
