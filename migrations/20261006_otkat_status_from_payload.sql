-- СРОЧНЫЙ ОТКАТ: триггер orders_status_from_payload снят.
--
-- Моя ошибка 06.10.2026. Я решил, что статус внутри заказа (raw_payload)
-- свежее колонки `status`, и поставил триггер, который приводит колонку к
-- заказу. Проверил гипотезу на двух заказах (54665, 54301) — там она
-- подтвердилась — и распространил на все, не проверив остальные.
--
-- На деле у части заказов наоборот: колонку обновляет приложение при смене
-- статуса, а внутри заказа остаётся старое значение. Из-за этого заказы,
-- переданные в производство, вернулись в «Счёт на оплате» (жалоба Евгении
-- Матвеевой и Елены Парфёновой 06.10.2026: 54932, 54131, 53666, 54691,
-- 54836).
--
-- Триггер снимаем: пока у статуса два места хранения, автоматически
-- выравнивать их нельзя — любое направление затирает чью-то правду.
-- Один источник статуса делается отдельной задачей.
-- ============================================================================

DROP TRIGGER IF EXISTS orders_status_from_payload ON public.orders;
DROP FUNCTION IF EXISTS public.orders_status_from_payload();
