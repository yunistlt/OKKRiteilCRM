-- Множитель нагрузки отдела: одна ручка вместо правки каждой нормы.
--
-- Нормы дня целые (12 задач, из них наших не больше 7), поэтому «прибавить
-- всем 5%» руками не получается: шаг 12 → 13 это сразу +8%. Множитель делает
-- шаг любым и обратимым — вернуть 1.00 можно в любой момент, базовые нормы не
-- тронуты.
--
-- Ставим 1.05 по просьбе владельца 02.09.2026: девочки успевают, день не полон.
-- Норма дня 12 → 13 задач, лимит наших задач 7 остаётся (7 × 1.05 = 7.35).
INSERT INTO public.sales_rop_settings (key, value, comment) VALUES
    ('load_factor', '1.05', 'Множитель нагрузки: 1.00 — базовые нормы, 1.05 — на 5% больше. Границы 0.5–2.0')
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, comment = EXCLUDED.comment;
