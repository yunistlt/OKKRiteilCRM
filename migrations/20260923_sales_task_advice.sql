-- Совет по задаче дня: что сделать, почему и что предложить.
--
-- Зачем. Строка «№54441 — 340 000 ₽ — ООО Ромашка / Счёт висит 5 дней» не
-- говорит менеджеру ничего, чего он не знает. За шестьдесят дней из 710 таких
-- задач в производство ушло 20 заказов, а в отмену 89 — причём половину
-- закрыли, ни разу не поговорив с клиентом. Список без смысла разгребают, а не
-- отрабатывают.
--
-- Таблица — кэш, а не журнал: совет пересчитывается, когда меняется состояние
-- заказа (отпечаток), и не пересчитывается каждое утро заново. Платить за
-- повторный разбор одного и того же незачем.

CREATE TABLE IF NOT EXISTS public.sales_task_advice (
    order_id      BIGINT NOT NULL,
    -- Один и тот же заказ в разные дни попадает в план по разным причинам, и
    -- совет для «счёт висит» не годится для «клиент давно молчит».
    reason_code   TEXT NOT NULL,
    action        TEXT NOT NULL,
    why           TEXT NOT NULL,
    offer         TEXT,
    -- Отпечаток состояния заказа: статус, срок, комментарии, звонки.
    fingerprint   TEXT NOT NULL,
    model         TEXT,
    generated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (order_id, reason_code)
);

ALTER TABLE public.sales_task_advice ENABLE ROW LEVEL SECURITY;

