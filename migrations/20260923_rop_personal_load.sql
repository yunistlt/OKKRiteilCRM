-- Личная нагрузка менеджера и возврат тихих отмен в работу.
--
-- 1. Нагрузка. Множитель load_factor был один на весь отдел: поднять Лене
--    значило поднять и Жене, у которой и так полный день. Теперь у каждого свой
--    коэффициент поверх общего. Пусто — работает общий, как раньше.
--
-- 2. Отмены. Заказ, закрытый без разговора с клиентом, возвращается в план на
--    следующий день и возвращается, пока разговора не будет. Не «напомнить», а
--    именно вернуть: за 60 дней так закрыли половину отменённых заказов, и это
--    потерянные клиенты, о которых мы даже не знаем, почему они ушли.
--
--    Порог даты обязателен. В «Согласовании отмены» висит 1798 заказов, и
--    вернуть их разом — значит завалить отдел списком, который не сделать, и
--    похоронить саму идею. Берём только те, что закрыты начиная с дня запуска;
--    старые разбираются отдельно, руками, и порог сдвигается по мере разбора.

ALTER TABLE public.sales_rop_manager
    ADD COLUMN IF NOT EXISTS load_factor NUMERIC(4,2);

COMMENT ON COLUMN public.sales_rop_manager.load_factor IS
    'Личный множитель нагрузки поверх общего. NULL — как у отдела.';

-- День, начиная с которого закрытые без разговора заказы возвращаются в план.
-- Ставится датой запуска, а не «минус 30 дней»: хвост разбирается руками.
INSERT INTO public.sales_rop_settings (key, value, comment)
VALUES (
    'cancel_return_since',
    to_char(now(), 'YYYY-MM-DD'),
    'Отмены раньше этой даты в план не возвращаются — хвост разбирается руками'
)
ON CONFLICT (key) DO NOTHING;

INSERT INTO public.sales_rop_settings (key, value, comment)
VALUES ('cancel_return_enabled', 'true', 'Возвращать ли в план заказы, закрытые без разговора с клиентом')
ON CONFLICT (key) DO NOTHING;

INSERT INTO public.sales_rop_settings (key, value, comment)
VALUES ('cancel_return_per_day', '3', 'Сколько таких заказов возвращать одному менеджеру за день')
ON CONFLICT (key) DO NOTHING;
