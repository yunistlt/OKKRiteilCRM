-- Карта решений по номенклатуре ЦехУспеха, а не по догадкам.
--
-- Проверено в производстве: скамьи и вешалки мы действительно делаем («Скамья с
-- вешалкой разборная», «Вешалка напольная двухсторонняя на 20 и 30 мест»), есть
-- отдельная «Рама подставки со скамьёй под шкаф 800х500» — то есть подставка под
-- сушильный шкаф, которая одновременно скамья. Есть гардеробные шкафы (СМО,
-- ШМИ), а к муфельным печам — огнеупорные шнуры, ленты и канальные вентиляторы.
--
-- Важный урок для будущих правок: искать по названиям деталей бесполезно, они
-- на техническом языке («Рама подставки 100х800х500»). Смотреть надо категории
-- производства — слова «скамейка» в деталях нет, а категория «Скамейки» есть.

UPDATE public.sales_solution_map SET
    offer_item = 'Подставка-скамья под шкаф',
    need_reason = 'Шкаф ставится на подставку, а подставка с сиденьем заодно решает, на чём детям сидеть при переобувании',
    availability = 'серийно',
    note = 'ЦУ: «Рама подставки со скамьей под шкаф 800х500», категория «Скамейки»'
 WHERE segment = 'Детский сад' AND offer_item = 'Скамейки в раздевалку';

