-- Алерт о неразобранных поступлениях: отметка о последнем напоминании.
-- ============================================================================
-- Контекст (инцидент 2026-08-01, платёж 1772 / заказ 53338):
--   Приход 331 834,58 ₽ от 22.07 не сматчился (в назначении счёт «5333» — на цифру
--   короче номера заказа 53338, плюс частичная оплата 70%) и десять дней молча лежал
--   в очереди «Требуют разбора». Уведомление в Telegram отправлялось ТОЛЬКО по
--   разнесённым платежам (status='matched'), поэтому о деньгах никто не узнал.
--
-- Колонка хранит время последнего напоминания по неразобранному платежу:
--   NULL                        — ещё не напоминали (первый алерт уйдёт ближайшим кроном);
--   старше PENDING_REMIND_HOURS — напомним снова (деньги висят, о них забыли).
-- Отдельная от notified_at: notified_at — «оплата разнесена», её нельзя занимать
-- напоминаниями, иначе разнос платежа останется без уведомления.
-- ============================================================================

ALTER TABLE public.point_payments
    ADD COLUMN IF NOT EXISTS pending_notified_at timestamptz;

COMMENT ON COLUMN public.point_payments.pending_notified_at IS
    'Когда в Telegram последний раз напоминали, что платёж требует ручного разбора (status=pending_match). NULL — ещё не напоминали.';

-- Выборка «кому напомнить» идёт по (status, pending_notified_at).
CREATE INDEX IF NOT EXISTS idx_point_payments_pending_notify
    ON public.point_payments (status, pending_notified_at)
    WHERE status = 'pending_match';
