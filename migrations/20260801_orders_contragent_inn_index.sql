-- Индекс по ИНН контрагента заказа — под матчинг платежей «по плательщику».
-- ============================================================================
-- Контекст: ИНН контрагента уже приезжает в orders.raw_payload->'contragent'->>'INN'
-- (заполнен у ~10 800 заказов), синкать его дополнительно не нужно. Не хватало только
-- поиска: старый фолбэк искал заказы по ТОЧНОЙ сумме и лишь потом сверял ИНН, поэтому
-- частичная оплата (предоплата 70% по заказу 53338) не находила заказ вообще.
--
-- Теперь матчинг спрашивает «какие заказы у этого ИНН ждут денег» — это запрос по
-- выражению, без индекса он даёт seq scan по всей таблице заказов на каждый платёж.
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_orders_contragent_inn
    ON public.orders ((raw_payload->'contragent'->>'INN'));

COMMENT ON INDEX public.idx_orders_contragent_inn IS
    'Матчинг банковских поступлений: заказы контрагента по ИНН плательщика (lib/payments/matching.ts).';
