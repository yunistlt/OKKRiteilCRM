-- Письмо клиенту при входе заказа в статус (доработка №94, Лена Парфёнова).
--
-- Просьба: «После перевода в статус ПЕРЕДАНО В ПРОИЗВОДСТВО писать
-- автоматические письма заказчику. Оплата поступила передали в производство».
-- В RetailCRM такое письмо слал триггер; у себя делаем так же, но без
-- хардкода статуса: какой статус шлёт письмо и каким шаблоном — настройка
-- самого статуса, как «Спрашивать причину словами» рядом.
--
-- Текст шаблона не выдуман: собран из писем, которые менеджеры пишут руками
-- (заказы 53058, 900503, 900553, 54534 — «Оплату видим / Заказ запущен в
-- производство / перед отгрузкой свяжется логист»).

ALTER TABLE public.crm_statuses
    ADD COLUMN IF NOT EXISTS client_email_template TEXT;

COMMENT ON COLUMN public.crm_statuses.client_email_template IS
    'Код шаблона из email_templates: письмо клиенту при входе заказа в этот статус. Пусто — письма нет.';

INSERT INTO public.email_templates (code, name, subject, body, active, sort_order, mode)
VALUES (
    'production-start',
    'Передано в производство',
    'Заказ №{{ order.number }} передан в производство',
    '<p>{{ greeting }}</p>' ||
    '<p>Оплату по заказу №{{ order.number }} получили, благодарим.</p>' ||
    '<p>Заказ запущен в производство.</p>' ||
    '<p>Перед отгрузкой с Вами свяжется наш логист: сориентирует по дате отгрузки и, если по заказу осталась доплата, напомнит о ней.</p>' ||
    '<p>Благодарим за заказ!</p>',
    true,
    70,
    'static'
)
ON CONFLICT (code) DO NOTHING;
