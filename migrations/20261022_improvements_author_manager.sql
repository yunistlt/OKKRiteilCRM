--
-- Зачем: когда владелец ставит «выполнено» с пояснением, пояснение уходит
-- автору в чат с Семёном (решение владельца 22.10.2026 по доработке №32:
-- «так и напиши в пояснениях и пусть бот ей отправит тоже эти пояснения»).
-- Адресата ищем по этому номеру; у старых записей он пустой — там адресата
-- добираем по почте автора.
ALTER TABLE public.improvements
    ADD COLUMN IF NOT EXISTS author_manager_id bigint;

COMMENT ON COLUMN public.improvements.author_manager_id IS
    'Менеджер RetailCRM, написавший доработку: ему уходит пояснение при отметке «выполнено».';
