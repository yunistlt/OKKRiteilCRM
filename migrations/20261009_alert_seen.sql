-- ============================================================================
-- Что человеку уже показывали во всплывающих оповещениях.
--
-- Помнить это должна система, а не браузер: у менеджера рабочий компьютер и
-- ноутбук, и память одного окна другому не помогает. К тому же любая
-- перерисовка страницы её теряла — оповещения лезли заново по письмам,
-- которые уже прочитаны, и по звонкам, которые давно кончились (жалоба Ирины
-- и Елены 09.10.2026: «ужасно мешает работать»).
--
-- Пишем сюда в момент выдачи: второй раз то же самое человек не увидит.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.alert_seen (
    id         BIGSERIAL PRIMARY KEY,
    -- Кому показали: почта или логин из сессии, как в остальных журналах.
    person     TEXT        NOT NULL,
    -- Ключ оповещения: «mail:<id>», «task-<id>», «call-<id>».
    alert_key  TEXT        NOT NULL,
    shown_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (person, alert_key)
);

CREATE INDEX IF NOT EXISTS alert_seen_person_idx
    ON public.alert_seen (person, shown_at DESC);
