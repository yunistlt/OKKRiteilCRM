--
-- В списке файлов заказа у вложений стояло сегодняшнее число (Андрей,
-- 27.10.2026): показывали `created_at`, то есть момент записи строки. Для
-- файла из письма полугодовой давности это вводит в заблуждение.
--
-- Для файлов, приложенных руками, колонка остаётся пустой — там дата записи
-- и есть дата появления файла.
ALTER TABLE order_files
    ADD COLUMN IF NOT EXISTS source_at timestamptz;
