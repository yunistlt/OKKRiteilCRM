-- Шаблон письма «Запрос контактного телефона».
--
-- Лена Парфёнова 28.10.2026 (доработка №59): «сделать шаблон письма на запрос
-- контактов. Примерно так: Здравствуйте, Вы прислали нам запрос на поставку
-- мебели. Пришлите пожалуйста свой контактный телефон для связи».
--
-- Текст её, приведён к виду остальных шаблонов: обращение по имени, если оно
-- известно, и номер заказа, чтобы письмо попало в переписку по заказу.
-- Шаблоны правятся в «Настройки → Шаблоны документов и писем»; менеджеру туда
-- нельзя, поэтому заводим здесь.
--
-- Проверено, что такого шаблона ещё нет (закон «проверь, что такого ещё нет»):
-- в email_templates нет кода, где речь о контактах — ближайший
-- `ai-requisites-request` про реквизиты, это другое.
-- ============================================================================
INSERT INTO public.email_templates (code, name, subject, body, mode, active, sort_order)
VALUES (
    'contacts-request',
    'Запрос контактного телефона',
    'Ваш запрос №{{ order.number }}: нужен контактный телефон',
    '<p>Здравствуйте{% if order.firstName %}, {{ order.firstName }}{% endif %}!</p>' || E'\n'
    || '<p>Вы прислали нам запрос на поставку мебели — он принят под номером {{ order.number }}.</p>' || E'\n'
    || '<p>Пришлите, пожалуйста, свой контактный телефон для связи: так быстрее уточним размеры, сроки и условия поставки.</p>',
    'static',
    true,
    (SELECT COALESCE(max(sort_order), 0) + 1 FROM public.email_templates)
)
ON CONFLICT (code) DO UPDATE
   SET name = EXCLUDED.name,
       subject = EXCLUDED.subject,
       body = EXCLUDED.body,
       mode = EXCLUDED.mode,
       active = true,
       updated_at = now();
