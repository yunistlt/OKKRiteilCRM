-- Время в задаче по заказу. Срок был только датой, а менеджеру нужно «перезвонить
-- в 14:30», а не «сегодня» (просьба Ирины Гордеевой 05.10.2026).
--
-- Добавляем отдельным полем, а не меняем тип due_date: дата остаётся датой,
-- старые задачи и индекс по сроку продолжают работать, время — необязательное.

ALTER TABLE public.order_tasks ADD COLUMN IF NOT EXISTS due_time TIME;

COMMENT ON COLUMN public.order_tasks.due_time IS 'Время срока задачи; пусто — срок на весь день';
