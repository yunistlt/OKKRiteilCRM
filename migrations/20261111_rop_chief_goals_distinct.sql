-- Цели в задании РОПа должны различаться.
--
-- Первый прогон с моделью (11.11.2026): у Матвеевой пять задач развития подряд
-- получили одну и ту же цель «назначена встреча», у трёх писем — «ответ
-- клиенту», у Гордеевой все пять задач — «узнать планы на будущие заказы».
-- Промпт требовал цель, но не требовал её различать, а одинаковая цель у всего
-- дня — это не задание, а заполненное поле.
--
-- ПРИМЕНЯТЬ ПОСЛЕ ВЫКАТА КОДА: вместе с этим уходит переписанный бриф
-- (lib/sales-rop/chief.ts), где рамки дня отделены от пула работы.

UPDATE public.ai_prompts
   SET system_prompt = system_prompt || E'\n\n'
        || E'ЦЕЛИ:\n'
        || E'— Цель у каждой работы своя. Две одинаковые цели в одном дне означают, что ты не думал: «назначена встреча» подряд у пяти клиентов — это не план.\n'
        || E'— Цель — проверяемый итог дня именно по этой работе: клиент назвал срок оплаты, получили заявку на просчёт, узнали, что мешает решению, договорились о дате отгрузки.\n'
        || E'— «Ответ клиенту», «назначена встреча», «узнать планы» целями не считаются: напиши, чего ждём от этого ответа и о чём договариваемся.\n'
        || E'— Если по работе ничего, кроме письма, сказать нельзя, то цель — что должно прийти в ответ на письмо.',
       updated_at = now()
 WHERE key = 'sales_rop_chief'
   AND system_prompt NOT LIKE '%ЦЕЛИ:%';
