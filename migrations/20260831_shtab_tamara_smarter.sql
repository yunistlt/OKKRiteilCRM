-- Штаб: поднять потолок рассуждения Тамары
--
-- Владелец: нужна максимально умная и рассудительная ассистентка. Разбор
-- показал, что настройки были перевёрнуты.
--
--   разговор с владельцем  — gpt-4o-mini, 900 токенов
--   понедельничная сводка  — gpt-4o-mini, 900 токенов
--   нарезка на блоки       — gpt-4o,     1600
--   написание программы    — gpt-4o,     3000
--
-- То есть самое сложное — разговор — досталось самой слабой модели. Написание
-- программы структурно проще: там схема структурированного вывода, пять типов
-- задач и проверки кодом (lib/shtab/program-checks.ts) ловят брак формы. А в
-- разговоре Тамара должна понять, чего владелец на самом деле спрашивает,
-- сообразить, какого факта не хватает, и задать один правильный вопрос вместо
-- того, чтобы додумать. Это работа для сильной модели.
--
-- 900 токенов — второй потолок. По-русски это примерно 400–600 слов: развернуть
-- довод на этом не получается, ответ обрывается на середине рассуждения.
--
-- Почему gpt-4.1, а не gpt-4o: больше окно контекста, а у Тамары длинный
-- системный промпт — правила, блок ПАМЯТЬ, выдержки знаний и история разговора.
--
-- Выбор модели — не окончательный. Это одно поле в ai_prompts, правится на
-- /settings/prompts без выкатки. Что доступно и почём — смотреть в личном
-- кабинете OpenAI: программного прайс-листа у него нет, и внутри системы
-- стоимость больше не считается.
--
-- Модели-рассуждатели (o-серия) сюда не берутся: runTamara всегда передаёт
-- temperature, которую часть таких моделей не принимает. Это правка кода и
-- отдельная проверка, а не строка в базе.
--
-- Миграция аддитивная и идемпотентная: только UPDATE существующих строк.

-- ── разговор: главное место, где нужна голова ────────────────────────────────
UPDATE public.ai_prompts
   SET model = 'gpt-4.1',
       max_tokens = 2500
 WHERE key = 'shtab_tamara_chat';

-- ── понедельничная сводка: она начинает разговор сама ────────────────────────
-- Здесь Тамара смотрит статистики и решает, о чём вообще говорить с владельцем
-- на этой неделе. Выбор темы — суждение, а не пересказ чисел.
UPDATE public.ai_prompts
   SET model = 'gpt-4.1',
       max_tokens = 2000
 WHERE key = 'shtab_tamara_briefing';

-- ── блоки и программы: туда же ───────────────────────────────────────────────
-- Одна модель на все четыре промпта: поведение ровное, и незачем держать два
-- разных набора привычек у одного консультанта.
UPDATE public.ai_prompts
   SET model = 'gpt-4.1'
 WHERE key IN ('shtab_tamara_blocks', 'shtab_tamara_program')
   AND model = 'gpt-4o';
