-- Один и тот же файл не ложится в заказ дважды.
--
-- Андрей 14.10.2026: «зачем мы делаем дубли файлов?» — в разделе «Файлы» каждый
-- файл шёл двумя одинаковыми строками. Решение: «не удалять, а просто
-- поставить пока галочку и запретить поиск по ним».
--
-- Причин было две. Форма письма заливала вложения из трёх мест (черновик,
-- подготовка во время отсчёта, отправка) с замком только на одном — вылечено в
-- коде. И перенос из RetailCRM, который прогнали дважды без проверки: 11 338
-- лишних строк, причём в 10 700 парах обе строки указывают на ОДИН И ТОТ ЖЕ
-- файл в хранилище — задвоены записи, не файлы.
--
-- Проверки в коде мало: два одновременных запроса оба читают «такого ещё нет» и
-- оба вставляют (воспроизведено 14.10.2026). Запрет должен стоять в базе.
--
-- Ничего не удаляется (ЗАКОН владельца 12.10.2026): лишние строки помечаются
-- архивными — пропадают из поиска, но открываются по галочке «показать
-- архивные», а файлы в хранилище остаются на месте.

-- 1. Лишние строки — в архив, оставляем самую раннюю из каждой группы.
WITH ranked AS (
    SELECT id,
           ROW_NUMBER() OVER (
               PARTITION BY order_number, file_name, size_bytes
               ORDER BY id
           ) AS rn
    FROM public.order_files
    WHERE deleted_at IS NULL
      AND archived_at IS NULL
      AND order_number IS NOT NULL
)
UPDATE public.order_files f
   SET archived_at = NOW(),
       archived_by = 'Дубль (разобрано 14.10.2026)'
  FROM ranked
 WHERE ranked.id = f.id
   AND ranked.rn > 1;

-- 2. Больше такого не повторится: в заказе один файл с таким именем и размером.
--    Архивные не в счёт — иначе нельзя снова приложить то, что раньше убрали.
CREATE UNIQUE INDEX IF NOT EXISTS order_files_no_dupes_idx
    ON public.order_files (order_number, file_name, size_bytes)
    WHERE deleted_at IS NULL AND archived_at IS NULL AND order_number IS NOT NULL;
