-- ============================================================================
-- Реестр доработок: куда сотрудники пишут, что доделать в системе.
--
-- Задание владельца 15.10.2026: «сделать реестр доработок, в левом меню
-- отдельную вкладку ДОРАБОТКИ. Нужно, чтобы девочки туда писали все доработки,
-- я буду его смотреть и после выполнения ставить отметку выполнено».
--
-- Состав полей — его же решение: текст, скриншот, ссылка на заказ и раздел
-- системы. Видят реестр все, отметку «выполнено» ставит только владелец,
-- выполненные уезжают вниз отдельным списком.
--
-- Таблицы под это не было: проверены `information_schema` по словам dorab,
-- improv, feedback, backlog, feature, request, suggest, wish, idea, todo, task
-- (ЗАКОН «проверь, что такого ещё нет»). Похожие `shtab_task` и `order_tasks` —
-- про другое: задачи владельца по заводу и задачи внутри заказа.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.improvements (
    id              bigserial PRIMARY KEY,

    -- Сама доработка, словами сотрудника.
    text            text        NOT NULL,

    -- Где в системе: путь раздела из меню («/orders»). Название показываем по
    -- нему же — имена разделов живут в lib/nav.ts, второй копии не заводим.
    section         text,

    -- Заказ, на котором это заметили. Номер, а не id: в интерфейсе он всегда
    -- ссылка (ЗАКОН «номер заказа — всегда ссылка»).
    order_number    text,

    -- Скриншот в бакете okk-assets — там же, где файлы заказов.
    screenshot_bucket text,
    screenshot_path   text,
    screenshot_name   text,

    -- Кто написал.
    author_email    text,
    author_name     text,
    created_at      timestamptz NOT NULL DEFAULT now(),

    -- Отметка «выполнено». Пусто — доработка в работе.
    done_at         timestamptz,
    done_by         text
);

-- Открытые сверху, свежие первыми: это единственный порядок, в котором реестр
-- читают.
CREATE INDEX IF NOT EXISTS idx_improvements_open
    ON public.improvements (created_at DESC)
    WHERE done_at IS NULL;

COMMENT ON TABLE public.improvements IS
    'Реестр доработок системы: сотрудники пишут, владелец отмечает выполненные (задание владельца 15.10.2026).';
