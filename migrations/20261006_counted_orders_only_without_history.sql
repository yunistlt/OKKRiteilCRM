-- ============================================================================
-- Засчитанная заявка: текущий статус берём только там, где истории нет.
--
-- Вопрос владельца 06.10.2026: «с сентябрём тоже не перевыполнили мы план, мы
-- его не довыполнили вообще. Истина вся в ритейле за сентябрь, мы ещё в
-- сентябре сидели. Какие статусы ты опять не туда гоняешь и не тем числом?»
--
-- Что было. Заказ считался ушедшим в производство двумя путями:
--   1) по истории — записан сам переход (за сентябрь таких 43, ровно столько
--      же, сколько даёт RetailCRM);
--   2) по текущему статусу — заказ СЕЙЧАС числится в производстве, а датой
--      входа бралось `statusUpdatedAt`.
--
-- Второй путь складывал статус с датой ЧУЖОГО перехода. Заказ 54665 стал
-- «Дублем заявки» 14.09 — и попадал в сентябрь как ушедший в производство
-- 14 сентября. Так же 54301 (дата перехода в «Предоплату» 30.09), 53666 и
-- 54131. Четыре лишние заявки давали отделу ~900 тыс. ₽ выручки, план
-- «выполнялся» на 100,07 %, и всем начислялся множитель x1,2.
--
-- Теперь второй путь работает, только когда истории статусов по заказу нет
-- вовсе — тогда дату входа взять действительно неоткуда. Есть история —
-- верим ей.
--
-- Сентябрь после исправления: 43 заявки, факт отдела 12 616 878 ₽ = 93 %
-- плана, множитель x1,05. ФОТ 284 503,74 ₽ вместо 341 119,24 ₽.
--
-- Текст функции целиком не дублируем: правка точечная, применена скриптом
-- поверх действующего определения (блок stat). Здесь — запись о том, что и
-- почему изменено.
-- ============================================================================

-- Проверка, что условие на месте: без него расчёт снова начнёт складывать
-- статус с чужой датой.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_proc
         WHERE proname = 'salary_counted_orders'
           AND prosrc LIKE '%Текущий статус берём ТОЛЬКО когда истории статусов%'
    ) THEN
        RAISE EXCEPTION 'salary_counted_orders: ветка stat не ограничена отсутствием истории';
    END IF;
END $$;
