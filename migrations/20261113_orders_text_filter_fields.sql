-- Какие поля карточки заказа ищутся подстрокой.
--
-- Доработка №92 (Ирина Гордеева, 10.11.2026): «не показывает дубли по городу,
-- заказы 900493 и 900176, в обоих Город доставки — Северск».
--
-- Причина: фильтр по полю карточки сверяет значение ЦЕЛИКОМ (jsonb-containment
-- по GIN-индексу). В одном заказе написано «АО «СХК» Росатом, Северск, Томская
-- область», в другом — «АО «СХК» Росатом Северск  Томская область». Для
-- человека это один адрес, для точного сравнения — две разные строки, и фильтр
-- не показывал ни одного из них.
--
-- Точное сравнение остаётся для полей-справочников: там значение выбирают из
-- списка, и подстрока только размывает выдачу. Текстовые поля человек набирает
-- руками, и искать в них надо по куску — как в поиске по заказам.
--
-- Список таких полей не выдуман и не зашит: это поля типа «строка» из
-- справочника полей RetailCRM, у которых есть своя колонка в `orders`. По
-- колонке подстрока идёт сканированием таблицы за 72 мс, по JSON — за 3,7 с
-- (замер 13.11.2026), поэтому поля без колонки остаются на точном сравнении.

CREATE OR REPLACE FUNCTION public.orders_text_filter_fields()
 RETURNS TABLE(code text)
 LANGUAGE sql
 STABLE
AS $function$
    SELECT DISTINCT f.code::text
      FROM public.retailcrm_custom_fields f
      JOIN information_schema.columns c
        ON c.table_schema = 'public'
       AND c.table_name = 'orders'
       AND c.column_name = f.code
       AND c.data_type IN ('text', 'character varying')
     WHERE f.type IN ('string', 'text')
       -- Только поля заказа: у карточки клиента есть свои поля с теми же
       -- именами («site» — адрес сайта клиента), и они к заказу отношения
       -- не имеют.
       AND f.entity = 'order';
$function$;

GRANT EXECUTE ON FUNCTION public.orders_text_filter_fields() TO service_role;
