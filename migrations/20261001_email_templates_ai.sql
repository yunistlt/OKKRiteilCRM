-- Шаблоны писем, которые пишет ИИ.
--
-- Было: шаблон — готовый текст с подстановками. Этого мало: письмо клиенту
-- зависит от того, что в заказе и о чём договаривались, а не только от номера.
-- Стало: у шаблона есть режим. Статический — как раньше. С промптом — ИИ пишет
-- письмо по данным заказа, менеджер правит руками перед отправкой
-- (требование владельца 01.10.2026).
--
-- Почему промпт в БД, а не в коде: это знание о том, как мы разговариваем с
-- клиентом, им владеет отдел продаж, и менять его должны без выкатки.

ALTER TABLE public.email_templates
    ADD COLUMN IF NOT EXISTS mode TEXT NOT NULL DEFAULT 'static',
    ADD COLUMN IF NOT EXISTS prompt TEXT;

COMMENT ON COLUMN public.email_templates.mode IS
  'static — готовый текст с подстановками; ai — письмо пишет ИИ по промпту';
COMMENT ON COLUMN public.email_templates.prompt IS
  'Задание для ИИ: о чём письмо, что обязательно сказать, чего не обещать';
