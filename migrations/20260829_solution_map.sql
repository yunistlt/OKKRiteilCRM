-- Карта решений: что клиенту нужно для его задачи.
--
-- Прежняя логика рекомендаций была статистической: «эти категории покупают одни
-- и те же клиенты». Она честно посчитана и бесполезна — из неё вышел совет
-- предложить фланцы покупателю сушильных шкафов, потому что 14 клиентов брали и
-- то и другое. Совпадение в таблице не означает, что вещи нужны вместе.
--
-- Правильная призма — потребность. Детский сад, купивший сушильный шкаф,
-- оснащает раздевалку: ему нужны скамейки и шкафчики. Лаборатория, купившая
-- муфельную печь, не может её просто поставить на стол: нужна подставка под
-- печь и вытяжка над ней. Это знание не выводится из наших продаж — его знает
-- тот, кто продаёт, и оно должно лежать в базе явно.
--
-- Поэтому таблица, а не промпт: карту правит человек, а не деплой, и у каждой
-- строки есть состояние — черновик или подтверждено. Модель берёт только
-- подтверждённые: непроверенная догадка в устах бота выглядит как знание.

CREATE TABLE IF NOT EXISTS public.sales_solution_map (
    id            bigserial PRIMARY KEY,
    -- Кого оснащаем: детский сад, лаборатория, автосервис, цех.
    segment       text NOT NULL,
    -- Что клиент уже взял (категория из sales_category_rule или свободный текст).
    trigger_item  text NOT NULL,
    -- Что предложить дополнительно.
    offer_item    text NOT NULL,
    -- Зачем это ему — фраза, которую менеджер может произнести вслух.
    need_reason   text NOT NULL,
    -- Производим серийно / делаем под заказ / не делаем.
    availability  text NOT NULL DEFAULT 'под заказ'
        CHECK (availability IN ('серийно', 'под заказ', 'не делаем')),
    -- draft — моя догадка, нужна проверка; confirmed — подтвердил владелец.
    state         text NOT NULL DEFAULT 'draft' CHECK (state IN ('draft', 'confirmed', 'rejected')),
    note          text NOT NULL DEFAULT '',
    updated_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (segment, trigger_item, offer_item)
);

CREATE INDEX IF NOT EXISTS idx_solution_map_lookup ON public.sales_solution_map (state, segment, trigger_item);

COMMENT ON TABLE public.sales_solution_map IS
    'Что предложить клиенту исходя из его задачи, а не из статистики совместных покупок. Модель использует только строки в состоянии confirmed.';

ALTER TABLE public.sales_solution_map ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS sales_solution_map_rw ON public.sales_solution_map;
CREATE POLICY sales_solution_map_rw ON public.sales_solution_map FOR ALL TO service_role USING (true) WITH CHECK (true);
GRANT ALL ON public.sales_solution_map TO postgres, service_role;
GRANT ALL ON SEQUENCE public.sales_solution_map_id_seq TO postgres, service_role;

