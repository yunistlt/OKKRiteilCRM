-- Место на печати юрлица: «Россия, Республика Татарстан, город Елабуга».
--
-- Решение владельца 02.10.2026: печати рисуем сами по образцам настоящих. На
-- них по нижней дуге стоит страна, регион и город, причём у ЗВТО это Татарстан
-- и Елабуга, а не Самарская область — значит место надо хранить по каждому
-- юрлицу, а не выводить из адреса продавца.
--
-- Заполняется вместе с подписантами кнопкой «Подписанты из ЕГРЮЛ»: регион и
-- город приходят из ЕГРЮЛ (Dadata).
--
-- Проверено перед добавлением: в legal_entities такой колонки нет.

ALTER TABLE public.legal_entities
    ADD COLUMN IF NOT EXISTS seal_place text;

COMMENT ON COLUMN public.legal_entities.seal_place IS
    'Страна, регион и город для нижней дуги печати. Заполняется из ЕГРЮЛ.';
