-- Договор по стандартной форме — свой статус в реестре юротдела.
--
-- Решение владельца 12.10.2026: кнопку «Отправить на согласование юристу» для
-- стандартных условий убираем, но договор всё равно ложится в реестр юриста —
-- молча, без действий со стороны менеджера.
--
-- Раньше такие договоры писались как «Согласован», хотя юрист их не видел и не
-- согласовывал. Теперь у них честный статус «По стандартной форме».

UPDATE public.order_contracts
   SET status = 'standard'
 WHERE status = 'approved'
   AND review_comment = 'Стандартные условия из списка — согласование юриста не требуется.';
