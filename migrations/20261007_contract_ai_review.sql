-- Замечания ИИ-юрисконсульта к договору.
--
-- Требование владельца 07.10.2026: «каждый договор должен быть
-- прокомментирован нашим ИИ-юристом, такая роль уже заведена в компании».
-- Роль — Лев, главный ИИ-юрисконсульт.
--
-- Храним рядом с самим договором: замечания относятся к конкретной его
-- редакции, и при пересоставлении должны обновляться вместе с текстом.
-- ============================================================================

ALTER TABLE public.order_contracts ADD COLUMN IF NOT EXISTS ai_review jsonb;
ALTER TABLE public.order_contracts ADD COLUMN IF NOT EXISTS ai_review_at timestamptz;

COMMENT ON COLUMN public.order_contracts.ai_review IS
    'Замечания ИИ-юрисконсульта (Лев) к этой редакции договора: {level, summary, notes, byAi}.';
