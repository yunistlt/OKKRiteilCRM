-- Задача РОПа: выполнить план и вести к стратегической цели, опираясь на
-- регламенты отдела.
--
-- Решение владельца 11.11.2026. До этого промпт объяснял, КАК выбирать день
-- (счёт вперёд, задача без разговора — не работа), но не говорил, ЗАЧЕМ: ни
-- плана, ни цели вдолгую, ни документов, по которым работает отдел. Поэтому
-- решения выходили аккуратными по форме и безразличными к результату месяца.
--
-- Регламенты, нормативы и скрипты бот читает из базы знаний Семёна (раздел
-- `sales-department`, 14 документов) — там же, откуда менеджер читает справку.
-- В промпт они не копируются: знания агентов живут в РАГ, иначе бот и человек
-- начнут работать по разным версиям одного регламента.
--
-- ПРИМЕНЯТЬ ПОСЛЕ ВЫКАТА КОДА: вместе с этим уходит бриф, который подаёт план,
-- цель, мотивацию, итоги недели, отпуска и сами документы.

INSERT INTO public.sales_rop_settings (key, value, comment)
VALUES (
    'strategic_goal',
    '300 постоянных клиентов со средним чеком 3 млн ₽ в год. Достигается не потоком заявок, а базой: клиент, третий год берущий один и тот же шкаф, — недоработанный клиент, а не лояльный.',
    'Куда отдел идёт вдолгую — вторая задача РОПа рядом с планом месяца'
)
ON CONFLICT (key) DO NOTHING;

UPDATE public.ai_prompts
   SET system_prompt = system_prompt || E'\n\n'
        || E'ЗАДАЧА:\n'
        || E'У тебя две задачи, и обе одновременно.\n'
        || E'1. Выполнить план месяца. По каждому дню спрашивай себя, приближает ли он план: ближе всего деньги там, где клиент уже согласился на цену.\n'
        || E'2. Вести отдел к стратегической цели. Она растёт не заявками, а постоянными клиентами, поэтому работу вдолгую нельзя не делать ни в один день — даже когда план горит.\n'
        || E'Решаешь ты не из головы: ниже даны регламенты, нормативы и скрипты отдела — те же, по которым работают менеджеры. Опирайся на них и называй документ там, где он решает дело («норматив: 60% разговоров до полудня»).\n'
        || E'Задание должно двигать то, за что менеджеру платят: чем ему платят, написано в брифе.\n'
        || E'Если менеджер скоро уходит в отпуск, день до отпуска другой: закрыть счета, договориться о сроках, передать горячее — а не начинать длинные разговоры.\n'
        || E'Если кто-то из отдела в отпуске, его горячие клиенты без присмотра: самое срочное можно отдать этому менеджеру.',
       updated_at = now()
 WHERE key = 'sales_rop_chief'
   AND system_prompt NOT LIKE '%ЗАДАЧА:%';
