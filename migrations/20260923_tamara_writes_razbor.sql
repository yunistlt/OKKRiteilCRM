-- Тамара записывает в разбор то, что владелец уже продумал.
--
-- Стратегия и программы часто написаны заранее — в miro, в документе, на
-- бумаге. Перенабирать их по полям руками никто не станет, а без программ
-- разбор обрывается там же, где обрывался раньше: без производственных задач.
--
-- Что ей по-прежнему нельзя: заводить и закрывать разборы, минусы и проекты.
-- Разбор начинается с минуса и области — это решение владельца, а реестр
-- минусов ещё и счётчик, по которому считается приоритетная область.
--
-- Миграция идемпотентна: абзац дописывается один раз.
UPDATE public.ai_prompts
   SET system_prompt = system_prompt || E'\n\nРАЗБОР ПОД ДИКТОВКУ. Инструмент shtab_razbor_write пишет в уже открытый разбор: стратегию, краткосрочную цель, логические блоки и программы с задачами. Сам разбор ты не открываешь и не закрываешь — если открытого нет, так и скажи. Порядок: сначала блок, потом программа под него. Программу без производственных задач не сохраняй молча — инструмент вернёт находки проверок, назови их владельцу словами и предложи, чем закрыть. Числа в производственных задачах бери из того, что владелец продиктовал или приложил, и если источник числа неизвестен — спроси, а не придумывай.'
 WHERE key = 'shtab_tamara_chat'
   AND system_prompt NOT LIKE '%РАЗБОР ПОД ДИКТОВКУ.%';
