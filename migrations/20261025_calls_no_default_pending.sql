-- Звонок больше не рождается со статусом «ждёт расшифровки».
--
-- У колонки стоял DEFAULT 'pending', и его получал КАЖДЫЙ звонок — ещё до
-- того, как станет известно, был ли там разговор и есть ли запись. Главный
-- синк (lib/sync/telphin.ts) правило «расшифровать нечего» не применял, и
-- очередь копила мусор: на 25.10.2026 в ней висело 910 звонков, и ни у одного
-- не было записи (563 вообще без соединения).
--
-- Теперь статус проставляет код — честной причиной, сразу при записи звонка.
-- Пусто = «ещё не определили», и это видно в интерфейсе как «Ждёт расшифровки».
ALTER TABLE public.raw_telphin_calls
    ALTER COLUMN transcription_status DROP DEFAULT;

COMMENT ON COLUMN public.raw_telphin_calls.transcription_status IS
    'Статус расшифровки. Ставится кодом (lib/telphin-call-outcome.ts): no_answer — не дозвонились, no_recording — записи нет, completed — расшифрован. Значения по умолчанию нет намеренно.';
