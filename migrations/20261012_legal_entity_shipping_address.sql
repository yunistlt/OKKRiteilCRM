-- Адрес отгрузки (склад) у нашего юрлица.
--
-- Ирина Гордеева 12.10.2026: «в КП только наш юридический адрес указан, а
-- нужен адрес отгрузки». Юридический адрес (ул. Революционная) и склад, откуда
-- забирают товар (ул. Ботаническая, 30А), — разные адреса; в условиях
-- самовывоза нужен второй.
--
-- Проверено перед созданием (закон «проверь, что такого ещё нет»): в
-- legal_entities адресных колонок нет вовсе, юридический адрес приезжает из
-- RetailCRM.

ALTER TABLE public.legal_entities
    ADD COLUMN IF NOT EXISTS shipping_address text;

COMMENT ON COLUMN public.legal_entities.shipping_address IS
    'Адрес отгрузки (склад): печатается в условиях самовывоза, не путать с юридическим';

-- Склад у завода один — заполняем всем активным юрлицам. Правится в
-- «Настройки → Наши юрлица».
UPDATE public.legal_entities
   SET shipping_address = 'г. Тольятти, ул. Ботаническая, 30А'
 WHERE shipping_address IS NULL AND active;
