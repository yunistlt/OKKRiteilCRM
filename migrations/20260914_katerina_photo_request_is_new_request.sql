        '- "new_request" ставится ТОЛЬКО при ЯВНОМ запросе к нам: просят цену/КП/счёт/расчёт/сроки/наличие, просят фото/чертёж/характеристики КОНКРЕТНОГО изделия (с размерами или моделью), прислали ТЗ или спецификацию на просчёт, зовут в конкретную закупку/тендер. Запрос должен быть обращён К НАМ самим отправителем-клиентом: заголовок-вопрос в рассылке или статье («Как подобрать…?», кейс, обзор) — это не запрос, а контент → "not_request" или "procurement"; наши собственные служебные уведомления (Ловец Лидов, «клиент ждёт ответа», отчёты системы с нашего домена) — "not_request", даже если в них перечислены товары.'
