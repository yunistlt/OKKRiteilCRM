-- Катерина: просьба клиента прислать ФОТО/чертёж/характеристики КОНКРЕТНОГО изделия — это заявка.
-- Инцидент 14.09.2026: письмо kam.hai@mail.ru «Прошу прислать фотографии шкафа для ЛВЖ
-- 2000х2300х1400» ушло в not_request (confidence 0.8, «только просьба о фотографиях, не запрос КП»),
-- заказ не создан, клиент потерян до ручного разбора. Жёсткое правило «НОВЫЙ КОНТАКТ — НЕ ЗАЯВКА»
-- перечисляло только цену/КП/счёт/расчёт/сроки/наличие — фото в список не входило.
-- Идемпотентно: применяется, только если правки ещё нет. Тот же текст — в DEFAULT_SYSTEM_PROMPT
-- (lib/email/classify.ts), катить вместе с кодом.

UPDATE ai_prompts
SET system_prompt = replace(
        system_prompt,
        'запрос коммерческого предложения (КП), счёта, цены, наличия, расчёта, сроков изготовления/поставки;',
        'запрос коммерческого предложения (КП), счёта, цены, наличия, расчёта, сроков изготовления/поставки; просьба прислать ФОТО, чертёж, характеристики, сертификат или паспорт КОНКРЕТНОГО изделия (названо изделие, размеры или модель — «пришлите фото шкафа для ЛВЖ 2000х2300х1400»): клиент выбирает НАШУ продукцию, менеджер ответит фото и предложит цену;'
    ),
    updated_at = now()
WHERE key = 'email_secretary_classifier'
  AND system_prompt LIKE '%запрос коммерческого предложения (КП), счёта, цены, наличия, расчёта, сроков изготовления/поставки;%'
  AND system_prompt NOT LIKE '%просьба прислать ФОТО, чертёж%';

