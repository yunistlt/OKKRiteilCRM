-- ============================================================================
-- Кому идёт КОПИЯ оповещения — настройкой, а не правкой кода.
--
-- 09.10.2026 копию «Заказ заведён в ЦехУспехе» в чат отдела продаж пришлось
-- убирать правкой каталога: менеджеры спрашивали «что это?», им это сообщение
-- не нужно. Адресация должна решаться настройкой (закон «куда слать решает
-- тип сообщения»), поэтому копия теперь живёт рядом с основным адресатом.
--
-- Пусто — берём из каталога. 'none' — копии нет вовсе.
-- ============================================================================

ALTER TABLE public.notification_routes
    ADD COLUMN IF NOT EXISTS copy_to TEXT;

COMMENT ON COLUMN public.notification_routes.copy_to IS
    'Кому копия: роль адресата, «none» — не отправлять, пусто — как в каталоге.';
