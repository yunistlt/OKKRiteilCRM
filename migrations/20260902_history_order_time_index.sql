-- Последнее касание по заказу — одним чтением индекса, а не сканом истории.
--
-- sales_rop_presale_orders берёт max(occurred_at) по каждому из ~820 заказов.
-- Индекс по retailcrm_order_id есть, но он не хранит порядок по времени, и на
-- каждый заказ читаются все его 72 записи истории: 21 704 буфера за прогон. На
-- прогретом кеше это 86 мс, на холодном проде — секунды, и 02.09.2026 запрос
-- упёрся в statement timeout. Отчёт вышел, но без имён менеджеров: все стали
-- «без менеджера».
--
-- Составной индекс отдаёт максимум первой же записью, без чтения остальных.
CREATE INDEX IF NOT EXISTS idx_order_history_order_time
    ON public.order_history_log (retailcrm_order_id, occurred_at DESC);
