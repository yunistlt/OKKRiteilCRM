-- Порядок блоков в шаблоне чата Тамары: вопрос уезжает в конец.
--
-- Кэш префикса у OpenAI работает слева направо: кэшируется ровно тот кусок
-- запроса, который совпал с предыдущим. Вопрос стоял первой строкой и менялся
-- каждую реплику, поэтому всё, что шло за ним, — знания, память, свод, файлы,
-- история — считалось свежим входом. На gpt-5.5 это 5 долларов за миллион
-- токенов против 0.50 за кэшированный.
--
-- Теперь первыми идут блоки, которые между репликами одного разговора не
-- меняются или растут только в конец (свод, файлы, история), за ними поиск по
-- вопросу, и сам вопрос последним. Смысл шаблона не меняется: модель читает
-- всё то же самое, просто в другом порядке, а вопрос в конце ей даже ближе.
UPDATE ai_prompts
SET user_prompt_template =
'Краткое содержание этого разговора:
{{summary_context}}

Файлы, приложенные к разговору:
{{files_context}}

Последние реплики этого разговора:
{{history_context}}

Знания по теме:
{{knowledge_context}}

Что отложилось из прошлых разговоров (память):
{{memory_context}}

Вопрос владельца: {{question}}',
    updated_at = NOW()
WHERE key = 'shtab_tamara_chat';
