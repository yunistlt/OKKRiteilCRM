-- Отказ клиента в разговоре снимает задачу — доработка №77.
--
-- Ирина Гордеева 03.11.2026: «клиент сказал, что нет потребности в нашей
-- продукции, уберите эту задачу». Снять задачу было нечем: заказа у такого
-- клиента нет, а менеджер планом не управляет. Решение принимает РОП — он и так
-- читает расшифровки вечером.
--
-- Разбор дня остаётся текстом для человека, а решения дописываются машинной
-- строкой в конец того же ответа: отдельный запрос стоил бы второго вызова
-- модели на каждого менеджера каждый вечер.
--
-- ПРИМЕНЯТЬ ТОЛЬКО ПОСЛЕ ВЫКАТА КОДА (lib/sales-rop/refusal.ts): до него строку
-- никто не разберёт, и она уедет людям в сообщение как есть.

UPDATE public.ai_prompts
   SET system_prompt = system_prompt || E'\n\n'
        || E'ОТКАЗЫ (машинная строка, последняя в ответе):\n'
        || E'— Если клиент в разговоре сказал, что продукция ему не нужна, добавь В САМОМ КОНЦЕ ответа одну строку:\n'
        || E'ОТКАЗЫ: [{"заказ":"номер заказа из строки звонка","горизонт":"сезон|год|никогда","слова":"как клиент это сказал"}]\n'
        || E'— «сезон» — не нужно сейчас, «год» — не нужно в этом году, «никогда» — не работают с такой продукцией вовсе.\n'
        || E'— Если номера заказа в строке звонка нет, вместо "заказ" поставь "телефон" с номером звонившего.\n'
        || E'— Отказ — это слова клиента о потребности, а не «перезвоните позже», «вышлите прайс» и не отказ от конкретной цены.\n'
        || E'— Эта строка не часть разбора: в тексте для менеджера про отказы не пиши, их он увидит отдельно.\n'
        || E'— Отказов не было — строку не добавляй вовсе.',
       updated_at = now()
 WHERE key = 'sales_call_day_review'
   AND system_prompt NOT LIKE '%ОТКАЗЫ (машинная строка%';

-- Настройки правила: отсрочки держим в базе, а не в коде.
INSERT INTO public.sales_rop_settings (key, value)
VALUES ('refusal_rule', 'true'),
       ('refusal_season_days', '120'),
       ('refusal_year_days', '365')
ON CONFLICT (key) DO NOTHING;
