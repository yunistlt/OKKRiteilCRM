-- ============================================================================
-- Признак «наше юрлицо» в карточке клиента.
--
-- Наши компании живут в базе дважды: карточкой клиента (в неё приходят заказы
-- между своими) и строкой в справочнике юрлиц (печать, подпись, реквизиты для
-- счёта). Документы — устав, ЕГРЮЛ, карточка предприятия — человек ищет там,
-- где открыл компанию, то есть в карточке клиента.
--
-- Решение владельца 08.10.2026: не заводить отдельный раздел, а поставить в
-- карточке клиента галочку «наше юрлицо» и показывать файлы прямо в ней.
-- ============================================================================

ALTER TABLE public.clients
    ADD COLUMN IF NOT EXISTS our_legal_entity_id BIGINT REFERENCES public.legal_entities(id);

COMMENT ON COLUMN public.clients.our_legal_entity_id IS
    'Наше юрлицо: связь карточки клиента со справочником юрлиц. Заполнено — в карточке видны документы компании и публичная ссылка /docs/<код>.';

CREATE INDEX IF NOT EXISTS clients_our_legal_entity_idx
    ON public.clients (our_legal_entity_id) WHERE our_legal_entity_id IS NOT NULL;
