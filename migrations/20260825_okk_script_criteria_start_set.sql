-- ── Стартовый набор = ровно эти 5 скрипт-критериев ──
-- Остальные скрипт-критерии выключаем (не удаляем: ключи есть в исторических score_breakdown).
UPDATE public.okk_criteria
SET is_active = false, updated_at = now()
WHERE eval_method = 'ai_script'
  AND key NOT IN (
      'script_offer_best_price',
      'script_offer_best_tech',
      'script_offer_best_terms',
      'script_company_info',
      'script_other_products'
  );
