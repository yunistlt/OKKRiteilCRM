-- ── 4. Деятельность компании ──
UPDATE public.okk_criteria SET
    label = 'Выяснена деятельность компании',
    category = 'Квалификация клиента',
    na_gate = 'production_or_cancel',
    ai_prompt = 'Проверь, стало ли понятно из разговора, чем занимается организация клиента: сфера деятельности или род бизнеса — торговля продуктами, общепит, аптека, пищевое производство, логистика, стройка, ферма, госзаказчик, оснащение вахтового посёлка и т.п.
TRUE, если сфера прозвучала в любой форме — прямым ответом на вопрос или косвенно («у нас на Сахалине продукты питания», «мы школы оснащаем»). Не важно, кто это озвучил: продавец или клиент.
FALSE, если: темы деятельности в разговоре не было вовсе; ИЛИ прозвучало только название организации без понимания рода деятельности; ИЛИ речь шла лишь о том, какое изделие нужно, без указания, для чего и в какой бизнес.
ВНИМАНИЕ: наша собственная компания (завод, ЗМК) организацией клиента НЕ является — слова о нашем производстве в зачёт не идут.',
    updated_at = now()
WHERE key = 'script_company_info';

