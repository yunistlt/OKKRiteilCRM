-- ── 1-3. Согласование параметров: цена / тех. характеристики / сроки ──
-- Ключи сохранены (в исторических score_breakdown и колонках okk_order_scores),
-- переформулированы промпты и человекочитаемые названия.

UPDATE public.okk_criteria SET
    label = 'Цена устраивает клиента',
    category = 'Согласование параметров',
    na_gate = 'approval_status',
    ai_prompt = 'Проверь, стало ли известно из разговора, что клиента УСТРАИВАЕТ наша цена. Ниже дано значение поля CRM «ТОП3 Проходим ли по цене» (Да / Нет / поле НЕ заполнено).
TRUE, если выполнено И то, И другое: (1) в разговоре прозвучало, что цена клиента устраивает — прямо («по цене нормально», «цена подходит», «берём по этой цене») либо клиент согласился после того, как продавец снял возражение по цене; (2) поле CRM заполнено значением «Да».
FALSE во всех остальных случаях, и в reason напиши, в каком именно:
- тему цены в разговоре не поднимали — reason: «цена с клиентом не обсуждалась»;
- клиент сказал, что цена его не устраивает / у конкурента дешевле, и согласия так и не прозвучало — reason: «клиента цена не устраивает: <цитата>»;
- из разговора видно, что цена устраивает, но поле CRM пустое — reason дословно: «вопрос задан и ответ получен, но в CRM не внесено»;
- значение поля CRM противоречит словам клиента — reason: «поле CRM противоречит ответу клиента».
Это НЕ про то, обосновывал ли продавец цену, — только про позицию клиента и её фиксацию в CRM.',
    updated_at = now()
WHERE key = 'script_offer_best_price';

