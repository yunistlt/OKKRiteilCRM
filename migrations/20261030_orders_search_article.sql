-- ============================================================================
-- Поиск заказов: обозначение изделия ищем целиком, а не по кускам.
--
-- Доработка №71, Ирина Гордеева 30.10.2026. Разбор и замеры — в комментарии к
-- переменной `strict` внутри функции, там же, где само правило.
--
-- Для запроса без пробелов: части не ищутся, и мало найти все части — они
-- должны стоять подряд. Остальное тело перенесено из
-- 20261020_orders_search_ranked.sql без правок.
--
-- Замер на боевой базе 30.10.2026, запрос «РШС-15-120-18»:
--
--   было   300 строк (потолок выдачи), из них с этим изделием 78
--   стало   78 строк, все с этим изделием
--   «стеллаж на 12 пар» — без изменений, 300
--
-- Проверялось чтением: прогнаны обе ветки и сверены номера заказов.
-- ============================================================================

CREATE OR REPLACE FUNCTION public.orders_search_ranked(q text, max_rows int DEFAULT 2000)
RETURNS TABLE (order_id bigint, rank int)
LANGUAGE plpgsql
STABLE
AS $function$
DECLARE
    -- Запрос без знаков препинания и регистра: «СТ-15» и «ст 15» — одно и то же.
    normalized text := btrim(regexp_replace(lower(coalesce(q, '')), '[^a-zа-яё0-9]+', ' ', 'g'));
    words text[];
    -- Самое длинное слово запроса: им отбираем кандидатов на неполное совпадение.
    anchor text;
    /**
     * Сколько заказов с НЕПОЛНЫМ совпадением разбираем.
     *
     * Заказы, где нашлись все слова, отбираются запросом по индексу и стоят
     * сверху — их считать дёшево (92 мс на боевой базе). Неполные совпадения
     * считаются перебором, а одно слово вроде «стеллаж» поднимает 6 088
     * заказов: разобрать их все — почти три секунды, а у базы слабый диск и
     * тяжёлый запрос в рабочее время останавливает отдел (закон владельца
     * 16.10.2026). Поэтому хвост ограничен: человеку нужны верхние строки, а
     * не весь перебор.
     */
    partial_limit int := 500;
    /**
     * Запрос без пробелов — это ОБОЗНАЧЕНИЕ изделия, а не набор слов.
     *
     * Ирина Гордеева 30.10.2026 (доработка №71): «поиск по названию очень плохо
     * работает. Ни разу не показал шкаф именно тот, который нужен РШС-15-120-18,
     * ищет только по буквам, не удобно искать заказ, когда проверяем на дубли».
     *
     * Что было: «РШС-15-120-18» резалось на ршс · 15 · 120 · 18, и в выдачу
     * шло всё, где нашлась половина кусков. Замер на боевой базе: 300 строк, из
     * них с этим обозначением — 78. Числа «15» и «18» есть в любом размере и
     * количестве, они и давали 222 лишних строки. Ирина сортирует список по
     * номеру заказа, чтобы видеть свежие, — при этом порядок по совпадению не
     * работает, и шум оказывается сверху. Отсюда «ни разу не показал».
     *
     * Обозначение человек вводит целиком, пробелов в нём нет. Для такого
     * запроса части не считаем: либо изделие нашлось, либо его в заказах нет.
     * Фразовый поиск («стеллаж на 12 пар») работает как работал — правило
     * владельца 20.10.2026 про порядок слов и знаки препинания в силе.
     */
    strict boolean := position(' ' in btrim(coalesce(q, ''))) = 0;
BEGIN
    IF normalized = '' THEN
        RETURN;
    END IF;

    words := regexp_split_to_array(normalized, ' ');
    SELECT w INTO anchor FROM unnest(words) AS w ORDER BY length(w) DESC LIMIT 1;

    RETURN QUERY
    WITH
    /**
     * Нашлись ВСЕ слова — самое полное совпадение. Порядок слов не важен:
     * каждое слово ищется само по себе, по gin_trgm индексу.
     */
    full_match AS (
        SELECT o.order_id,
               /**
                * Слова идут подряд — это точное попадание, оно выше прочих.
                * Сравниваем по тексту без знаков препинания: «Вираж-Стандарт»
                * и «вираж стандарт» — одно и то же. Приведение к такому виду
                * дорогое, поэтому делаем его только здесь, на строках, где уже
                * нашлись все слова.
                */
               (CASE WHEN x.phrase THEN 1100 ELSE 1000 END) AS rank
        FROM public.orders o
        CROSS JOIN LATERAL (
            SELECT position(normalized in regexp_replace(
                       lower(coalesce(o.search_text, '') || ' ' || coalesce(o.items_text, '')),
                       '[^a-zа-яё0-9]+', ' ', 'g')) > 0 AS phrase
        ) x
        WHERE NOT EXISTS (
            SELECT 1 FROM unnest(words) AS w
            WHERE coalesce(o.search_text, '') NOT ILIKE '%' || w || '%'
              AND coalesce(o.items_text, '') NOT ILIKE '%' || w || '%'
        )
          AND (coalesce(o.search_text, '') ILIKE '%' || anchor || '%'
               OR coalesce(o.items_text, '') ILIKE '%' || anchor || '%')
          /**
           * У обозначения мало найти все части — они должны стоять подряд.
           * Иначе «РШС-15-120-18» ловит «SL1 Вираж-Стандарт на 15 пар», где
           * 15, 120 и 18 разбросаны по размерам и количеству: все четыре части
           * есть, изделие другое. Замер: таких строк 17 из 95, и при сортировке
           * по номеру они встают первыми — ровно то, на что жалуется Ирина.
           */
          AND (NOT strict OR x.phrase)
        LIMIT max_rows
    ),
    -- Нашлась часть слов: ниже полных совпадений, между собой — по числу слов.
    candidates AS (
        SELECT o.order_id, o.search_text, o.items_text
        FROM public.orders o
        WHERE NOT strict
          AND (coalesce(o.search_text, '') ILIKE '%' || anchor || '%'
               OR coalesce(o.items_text, '') ILIKE '%' || anchor || '%')
          AND o.order_id NOT IN (SELECT f.order_id FROM full_match f)
        LIMIT partial_limit
    ),
    partial_match AS (
        SELECT c.order_id, m.matched * 10 AS rank
        FROM candidates c
        CROSS JOIN LATERAL (
            SELECT count(*)::int AS matched
            FROM unnest(words) AS w
            WHERE coalesce(c.search_text, '') ILIKE '%' || w || '%'
               OR coalesce(c.items_text, '') ILIKE '%' || w || '%'
        ) m
        /**
         * Половина слов — порог. Заказ, где нашлось одно слово из четырёх, —
         * это не ответ на запрос, а шум: по «стеллаж на 12 пар» такого
         * «найденного» набиралось восемь сотен, и человеку приходилось
         * выбирать нужное глазами.
         */
        WHERE m.matched * 2 >= array_length(words, 1)
    )
    SELECT m.order_id, m.rank::int
    FROM (
        SELECT f.order_id, f.rank FROM full_match f
        UNION ALL
        SELECT p.order_id, p.rank FROM partial_match p WHERE p.rank > 0
    ) m
    ORDER BY m.rank DESC, m.order_id DESC
    LIMIT max_rows;
END;
$function$;

COMMENT ON FUNCTION public.orders_search_ranked(text, int) IS
    'Поиск заказов по покупателю и составу: прямое вхождение знаков, без учёта регистра и пунктуации, порядок слов не важен. Ранг — число совпавших слов, вся фраза целиком даёт бонус. Запрос без пробелов считается обозначением изделия: части не ищутся.';
