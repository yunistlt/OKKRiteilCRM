-- ИИ-РОП решает день: журнал решений, настройки и промпт.
--
-- Было: план собирал код целиком — отбирал кандидатов по порогам, резал нормой
-- и сортировал, а модель подписывала к готовой строке «о чём говорить».
-- Руководителя в этом не было ни на одном шаге, и видно это было по данным:
-- один клиент приходил в план 32 дня подряд, разговор случался в 3% задач
-- блока развития, а услышанный отказ не влиял ни на что, кроме одного блока.
--
-- Стало: код собирает факты и держит сторожей, решение принимает Роман. Один
-- вызов модели на менеджера в сутки вместо вызова на каждую задачу.
--
-- ПРИМЕНЯТЬ ТОЛЬКО ПОСЛЕ ВЫКАТА КОДА (lib/sales-rop/chief.ts): промпт без кода
-- некому читать. Включение всё равно двухступенчатое — chief_enabled выключен,
-- chief_shadow включён, то есть сперва только журнал.

-- Журнал решений: что РОП решил, что из этого взяли и что срезали сторожа.
-- Нужен, чтобы любое число в плане раскладывалось до исходного решения, и
-- чтобы теневой режим было с чем сравнивать.
CREATE TABLE IF NOT EXISTS public.sales_rop_chief_decision (
    plan_date   date NOT NULL,
    -- Менеджер обязателен: день без адресата не ставят, а заказы уволенных
    -- уходят владельцу отдельным блоком (ЗАКОН: заявка всегда с менеджером).
    manager_id  integer NOT NULL,
    pool_size   integer NOT NULL DEFAULT 0,
    model       text,
    -- Ответ модели как пришёл: по нему потом видно, что именно она решала.
    decision    jsonb NOT NULL DEFAULT '{}'::jsonb,
    -- Ключи работ, которые в итоге ушли в план.
    taken       text[] NOT NULL DEFAULT '{}',
    -- Что сторожа не пропустили: выдуманная работа, перебор нормы, отсрочка
    -- живой сделки. Пусто — решение применено целиком.
    violations  text[] NOT NULL DEFAULT '{}',
    -- false — теневой режим: решение записано, людям ушёл план по правилам.
    applied     boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (plan_date, manager_id)
);

COMMENT ON TABLE public.sales_rop_chief_decision IS
    'Решения ИИ-РОПа по дню: пул, выбор, отсрочки и срезанное сторожами.';

