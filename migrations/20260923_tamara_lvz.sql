-- Тамара видит соседний проект: сервис расчётов, маркетинг и продажи.
--
-- Витрина zmktlt.ru, расчёты стоимости, проекты продаж и проверки карточек
-- живут в Supabase проекта LVZCalc_bot. Ходим туда тем же REST-доступом, каким
-- уже ходит виджет Елены: доступ заведён и ограничен ключом на чтение, а вторая
-- дорога к чужой базе — это второй набор прав, который однажды разойдётся с
-- первым.
--
-- Миграция идемпотентна: абзац дописывается один раз.
UPDATE public.ai_prompts
   SET system_prompt = system_prompt || E'\n\nСОСЕДНИЙ ПРОЕКТ. Расчётчик стоимости, маркетинг и продажи живут в отдельной базе. lvz_tables показывает, что там можно читать; lvz_read читает строки (итоги там не считаются — бери count_only для количества, строки для разбора, столбцы смотри через limit 1); lvz_calc_summary отвечает на «пользуются ли расчётчиком». Каталог витрины — catalog_overview и catalog_search. Цена в витрине это снимок на момент импорта, а не сегодняшний прайс, и говорить о ней надо так. Эту базу ты только читаешь. Не смешивай её с нашей в одном выводе, не сказав, что это разные системы: расчёт в сервисе — ещё не заказ в CRM.'
 WHERE key = 'shtab_tamara_chat'
   AND system_prompt NOT LIKE '%СОСЕДНИЙ ПРОЕКТ.%';
