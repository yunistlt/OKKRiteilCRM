-- ИИ-РОП заводит заказ по звонку с незнакомого номера, если менеджер его не завёл.
--
-- Путь: входящий с номера, по которому заказов нет → менеджер поговорил →
-- расшифровка → ждём, пока менеджер заведёт заказ сам → не завёл и ИИ-РОП
-- считает, что это новый запрос на нашу продукцию → заказ «Новая» на того, кто
-- говорил, звонок привязывается к нему.
--
-- Всё аддитивно: новая таблица, новые ключи настроек (выключено), новый промпт.

-- Журнал решений: по одной строке на звонок — и «завёл», и «пропустил», с причиной.
-- Уникальность по звонку — она же защита от двойного заказа при повторном проходе.
CREATE TABLE IF NOT EXISTS public.call_lead_reviews (
    id              BIGSERIAL PRIMARY KEY,
    telphin_call_id TEXT NOT NULL UNIQUE,
    call_started_at TIMESTAMPTZ,
    phone           TEXT,
    manager_id      INTEGER,
    -- created — завели заказ; skipped — не заводили (причина в reason); error — сбой, будет повтор
    decision        TEXT NOT NULL CHECK (decision IN ('created', 'skipped', 'error')),
    -- что за разговор по мнению модели (new_request, existing_order, supplier, …) или код пропуска до модели
    category        TEXT,
    reason          TEXT,
    summary         TEXT,
    order_id        BIGINT,
    model           TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS call_lead_reviews_created_at_idx ON public.call_lead_reviews (created_at DESC);

COMMENT ON TABLE public.call_lead_reviews IS
    'ИИ-РОП: разбор звонков с незнакомых номеров — завёл ли заказ и почему. Одна строка на звонок.';

