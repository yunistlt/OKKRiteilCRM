-- ============================================================================
-- Окно звонка живёт столько, сколько идёт разговор.
--
-- Жалоба владельца 15.10.2026: «время отображения попапа звонка надо на время
-- длительности звонка».
--
-- Что происходило. Один звонок у Телфина — это несколько НОГ (SubCallID): нога
-- клиента и по ноге на каждый добавочный очереди. Завершение Телфин присылает
-- на КАЖДУЮ ногу отдельно, а наш обработчик на любой `hangup` удалял строку
-- целиком. Живой входящий 15.10.2026 (CallID 5d806483…, разговор 17,6 с):
--
--   11:13:57  dial-in                                 → окно появилось
--   11:14:03  hangup  CHANUNAVAIL  0 с  (добавочный 103 не поднял трубку)
--                                                     → окно ПОГАСЛО
--   11:14:14  hangup  ANSWER      17,6 с              ← вот когда звонок кончился
--
-- То есть окно жило шесть секунд из семнадцати, а при звонке на очередь — одну:
-- остальные добавочные отбиваются сразу, как только трубку снял кто-то один.
--
-- Чтобы отличить отбой одной ноги от конца разговора, храним список открытых
-- ног. Нога открывается на `dial-*`, закрывается на своём `hangup`; окно гаснет,
-- когда закрылась последняя, либо сразу — когда пришёл `hangup` ноги, которая
-- РАЗГОВАРИВАЛА (CallStatus=ANSWER): это и есть конец разговора.
-- ============================================================================

ALTER TABLE public.active_calls
    ADD COLUMN IF NOT EXISTS legs text[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN public.active_calls.legs IS
    'Открытые ноги звонка (SubCallID Телфина): нога клиента и по ноге на каждый добавочный. Пусто — звонок закончился, окно гаснет.';
