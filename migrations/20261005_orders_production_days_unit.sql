-- Срок изготовления: рабочие или календарные дни (просьба Евгении Матвеевой
-- 05.10.2026 — «80» в карточке не говорит, какие это дни). Единица идёт в КП,
-- счёт и договор.
--
-- Поле наше, в RetailCRM его нет, поэтому синхронизация его не трогает.
-- Пусто — календарные: так написано в прежних КП и договорах («30 календарных
-- дней»), и старые заказы менять задним числом нельзя.
ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS srok_izgot_edinica text;

COMMENT ON COLUMN public.orders.srok_izgot_edinica IS
    'Единица срока изготовления: rabochie | kalendarnye; пусто — календарные';
