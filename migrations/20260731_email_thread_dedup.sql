-- Катерина: борьба с дублями заявок.
-- За 60 дней менеджеры пометили «Дубль заявки» 78 из 399 заказов, созданных секретарём (20%).
-- Калибровка на этой разметке показала: сходство текста писем НЕ разделяет дубль и законную
-- повторную заявку того же клиента (медиана сходства 0.79 против 0.80 — при любом пороге ~50/50).
-- Единственный разделяющий признак — общий почтовый ТРЕД: 21% дублей против 4% законных.
--
-- Отсюда два порога:
--   thread_dedup_days   — окно жёсткого тред-дедупа: письмо продолжает тред, по которому заказ уже
--                         создан → новый заказ не заводим, письмо и вложения идут в тот заказ;
--   duplicate_hint_days — окно мягкой пометки: у клиента уже есть заказ за этот срок → заказ всё
--                         равно создаём (иначе теряем законные заявки), но помечаем менеджеру.

ALTER TABLE public.email_intake_config
    ADD COLUMN IF NOT EXISTS thread_dedup_days INTEGER NOT NULL DEFAULT 14,
    ADD COLUMN IF NOT EXISTS duplicate_hint_days INTEGER NOT NULL DEFAULT 14;

-- Мягкая пометка ищет последний заказ клиента по email внутри raw_payload — без индекса это
-- полный скан orders (ср. индекс orders(number), добавленный после таймаута ведомости ЗП).
CREATE INDEX IF NOT EXISTS idx_orders_raw_email_created
    ON public.orders ((raw_payload->>'email'), created_at DESC);
