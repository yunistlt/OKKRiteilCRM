-- Статус, в который нельзя перевести заказ без причины словами.
--
-- Решение владельца 05.10.2026: как было в RetailCRM — при смене статуса
-- всплывает окно с текстовым полем, и в «Согласование отмены» без заполненной
-- причины не пускаем. Запрет — не зашитый в код список, а галочка в карточке
-- статуса: завтра такой же запрет понадобится другому статусу.
--
-- Галочка живёт в карточке статуса (crm_statuses), рядом с «Рабочий статус»:
-- отдельную таблицу не заводим — закон «проверь, что такого ещё нет».
ALTER TABLE public.crm_statuses
    ADD COLUMN IF NOT EXISTS requires_reason boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.crm_statuses.requires_reason IS
    'Перевод в этот статус требует причины словами (спрашиваем окном, пишем в историю).';

-- Тот самый статус, ради которого правило и заводили.
UPDATE public.crm_statuses SET requires_reason = true WHERE code = 'soglasovanie-otmeny';
