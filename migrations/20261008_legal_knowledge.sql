-- ============================================================================
-- База знаний юротдела: по каким правилам ИИ-юрисконсульт проверяет договор.
--
-- До этого Лев получал только текст договора и писал общими словами
-- («обратите внимание на сроки»), потому что не знал, что для нас норма.
-- Правила выведены из 234 наших договоров и протоколов разногласий за
-- 2020–2026 годы (разбор 08.10.2026).
--
-- Каждое правило — отдельная строка, чтобы владелец и юрист правили их в
-- интерфейсе, а не в коде (закон «без хардкода»). У правила есть основание:
-- на скольких договорах оно замечено.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.legal_knowledge (
    id bigserial PRIMARY KEY,
    /** Раздел договора: оплата, сроки, неустойка, подсудность, приёмка… */
    topic text NOT NULL,
    /** Само правило, человеческим языком — его читает и модель, и юрист. */
    rule text NOT NULL,
    /**
     * Насколько жёстко.
     * red — красная линия, так подписывать нельзя;
     * watch — повод насторожиться и показать живому юристу;
     * norm — наша обычная практика, отклонение стоит объяснить.
     */
    severity text NOT NULL DEFAULT 'watch',
    /** На чём основано: цифры из разбора наших же договоров. */
    evidence text,
    is_active boolean NOT NULL DEFAULT true,
    created_by text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.legal_knowledge IS
    'Правила юротдела для ИИ-юрисконсульта: что для нас норма, что повод насторожиться, что подписывать нельзя.';

CREATE INDEX IF NOT EXISTS legal_knowledge_active_idx ON public.legal_knowledge (is_active, topic);
