-- Катерина: в бухгалтерию — только вопросы по ДОКУМЕНТАМ; запрос цены/сроков/КП = заявка.
-- Плюс новое поле ответа new_inquiry (конкретный новый запрос на просчёт) — воркер использует его,
-- чтобы не терять заявку, пришедшую ответом в старой переписке.
-- Инцидент 11.08.2026: письмо «RE: RE: Запрос КП 51672 … с НДС 5%» с запросом цены на шкаф
-- «Топтыжка 4» (20 шт, Нефтеюганск) ушло в бухгалтерию, заявка не создалась.
-- Идемпотентно: правки применяются только если их ещё нет.

UPDATE ai_prompts
SET system_prompt = replace(
        system_prompt,
        'Бухгалтерия начинается там, где счёт уже выставлен.',
        'Бухгалтерия начинается там, где счёт уже выставлен.' || E'\n' ||
        '   НИКОГДА не "accounting", если клиент спрашивает ЦЕНУ, СРОК ИЗГОТОВЛЕНИЯ, НАЛИЧИЕ, РАСЧЁТ или просит КП — это "new_request", даже если в теме есть «НДС 5%», «Коммерческое предложение», номер заказа или «Re:». Слова «НДС», «счёт», «оплата» в ТЕМЕ (тема часто наша же, из старой переписки) бухгалтерией письмо не делают — смотри, что клиент СПРАШИВАЕТ В ТЕЛЕ письма.'
    ),
    updated_at = now()
WHERE key = 'email_secretary_classifier'
  AND system_prompt LIKE '%Бухгалтерия начинается там, где счёт уже выставлен.%'
  AND system_prompt NOT LIKE '%НИКОГДА не "accounting"%';

UPDATE ai_prompts
SET system_prompt = replace(
        system_prompt,
        '  "order_number":',
        '  "new_inquiry": true, // Суди ТОЛЬКО по блоку «НОВЫЙ ТЕКСТ ОТПРАВИТЕЛЯ» (если его нет — по телу письма): true, только если там КОНКРЕТНЫЙ новый запрос на просчёт — названо изделие и указано количество, габариты/характеристики или объект («подскажите цену и сроки на … — 20 шт», список позиций, ТЗ во вложении). false — если это уточнение по уже обсуждаемому (скидка, обрешётка, реквизиты, статус, «актуально», «неактуально», «когда ответ?»), вопрос по документам или письмо не от клиента. Запросы из ЦИТАТЫ старой переписки не считаются' || E'\n' ||
        '  "order_number":'
    ),
    updated_at = now()
WHERE key = 'email_secretary_classifier'
  AND system_prompt LIKE '%  "order_number":%'
  AND system_prompt NOT LIKE '%"new_inquiry"%';
