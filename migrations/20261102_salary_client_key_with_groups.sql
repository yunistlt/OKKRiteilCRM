-- ============================================================================
-- Группа компаний снова определяет, кто покупатель, в зарплате.
--
-- Что сломалось. 14.10.2026 ключ клиента перевели на ИНН контрагента
-- (`salary_order_client`, миграция 20261014_permanent_client_by_payment.sql).
-- Группы компаний остались в функции `salary_canon_client`, а её с того дня
-- не зовёт ни одна функция и ни одно представление — группы выпали из
-- расчёта целиком.
--
-- Чем это обернулось. Менеджеры собрали 11 групп, семь из них зарплата
-- видит как несколько разных клиентов: «ООО Дети наше будущее» — шесть
-- оплаченных заказов на пяти ключах. Заказ 41989 (26.10.2026, Евгения
-- Матвеева) засчитался первой покупкой клиента вместо шестой: доплата за
-- 6-ю покупку 10 000 ₽ не начислена, ставка за заявку ушла как «новый»
-- (2 300 вместо 3 800). Ещё три заказа октября занижены на одну покупку:
-- 900050 (СКС), 900089 (ИП Пижамов), 53505 (КВАДРО) — по 3 000 ₽.
--
-- Решение владельца 02.11.2026: вернуть группу в ключ клиента.
--
-- Как считается ключ теперь:
--   1) группа компаний, если карточка заказа в ней состоит;
--   2) иначе ИНН контрагента — склейка карточек одного юрлица;
--   3) иначе номер карточки.
--
-- Группа владеет не карточками, а КЛЮЧАМИ своих карточек. Иначе заказ
-- другой карточки с тем же ИНН остался бы на ИНН-ключе, и склейка по ИНН,
-- работавшая до сих пор, развалилась бы ровно там, где завели группу.
--
-- Ключ группы — отрицательный номер группы: диапазоны не пересекаются
-- (ИНН — 10–12 цифр, карточки — пятизначные и свои 900 000 xxx). Ключ
-- нигде не показывается человеку: в ведомости клиент выводится именем.
--
-- Закрытые периоды держат снимок и не меняются. Открытые (октябрь, ноябрь)
-- пересчитаются сами.
-- ============================================================================

CREATE OR REPLACE VIEW public.salary_order_client AS
WITH b2 AS (
    SELECT o.order_id,
           o.customer_id,
           CASE WHEN regexp_replace(COALESCE(o.contragent->>'INN', ''), '\D', '', 'g') ~ '^[0-9]{10,12}$'
                THEN regexp_replace(o.contragent->>'INN', '\D', '', 'g') END AS inn
    FROM public.orders o
    WHERE o.customer_id IS NOT NULL
),
-- Единственный ИНН карточки: им закрываем её же заказы, где ИНН не проставлен.
card_inn AS (
    SELECT customer_id, min(inn) AS inn
    FROM b2 WHERE inn IS NOT NULL
    GROUP BY customer_id HAVING count(DISTINCT inn) = 1
),
keyed AS (
    SELECT b2.order_id, b2.customer_id, COALESCE(b2.inn, ci.inn) AS inn
    FROM b2 LEFT JOIN card_inn ci ON ci.customer_id = b2.customer_id
),
-- Ключ без учёта групп: ИНН числом, а у кого ИНН нет — номер карточки.
base AS (
    SELECT k.order_id,
           k.customer_id,
           k.inn,
           COALESCE(k.inn::bigint, k.customer_id) AS plain_key
    FROM keyed k
),
-- Ключи, которые принадлежат группе: все ключи её карточек. Карточка с
-- несколькими ИНН приносит в группу каждый из них.
group_keys AS (
    SELECT b.plain_key, min(m.group_id) AS group_id
    FROM public.company_group_members m
    JOIN base b ON b.customer_id = m.client_id
    GROUP BY b.plain_key
)
SELECT b.order_id,
       COALESCE(-g.group_id, b.plain_key) AS client_key,
       COALESCE('grp:' || g.group_id, 'inn:' || b.inn, 'cust:' || b.customer_id) AS group_key
FROM base b
LEFT JOIN group_keys g ON g.plain_key = b.plain_key;

COMMENT ON VIEW public.salary_order_client IS
    'Кто клиент заказа для зарплаты: группа компаний, иначе ИНН контрагента, иначе карточка.';
