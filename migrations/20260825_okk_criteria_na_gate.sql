-- Стартовый набор скрипт-критериев ОКК по канону «один факт — одно правило»
-- (docs/okk/CRITERIA_V2.md). Аддитивно: новая колонка na_gate + переформулировка
-- активных критериев + один новый ключ. Данные не удаляются.
--
-- na_gate — код СИСТЕМНОГО гейта применимости критерия. Гейт считает код (детерминированно
-- по статусам заказа), а не ИИ. Если гейт не пройден — критерий = null («не применяется»),
-- вне знаменателя балла и без штрафа. Поддерживаемые коды (lib/okk-evaluator.ts):
--   'approval_status'      — заказ дошёл до «Согласование параметров заказа» или дальше
--   'production_or_cancel' — заказ дошёл до производства/доставки/выполнения или отменён

ALTER TABLE public.okk_criteria ADD COLUMN IF NOT EXISTS na_gate text;

COMMENT ON COLUMN public.okk_criteria.na_gate IS
    'Код системного гейта применимости: approval_status | production_or_cancel | NULL (всегда применяется)';
