-- ============================================================================
-- Номер заказа — опорный ключ. Делаем его уникальным в базе.
--
-- Закон владельца 09.10.2026: заказ уникален своим номером, номер заводится в
-- одном месте при создании и дальше транслируется во все связанные таблицы.
-- До сих пор это держалось на договорённости: уникального индекса не было, и
-- база спокойно принимала второй такой же номер.
--
-- Что мешало. RetailCRM нумерует заказы внутри магазина, и три пары заказов
-- 2020–2021 годов получили одинаковые номера в разных витринах
-- (`zmktlt-ru` и `zmktlt-ru-admin`):
--     1002867 — заказы 10131 и 10166
--     1002984 — заказы 12627 и 12630
--     1003012 — заказы 13546 и 13549
-- Ссылок на них нет нигде: ни писем, ни звонков, ни файлов, ни задач, ни
-- договоров (проверено перед правкой). Решение владельца — перенумеровать
-- лишний заказ пары, сохранив сам заказ, его сумму и историю.
--
-- Новый номер даём из свободного диапазона 910000+: он не пересекается ни с
-- номерами RetailCRM (сейчас ~55 тысяч), ни с нашими (900001+). Прежний номер
-- остаётся виден в поле «старый номер», чтобы заказ можно было найти по нему.
-- ============================================================================

ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS legacy_number TEXT;

COMMENT ON COLUMN public.orders.legacy_number IS
    'Прежний номер заказа, если его пришлось сменить ради уникальности. Для поиска по старым документам.';

-- Перенумеровываем ровно те заказы, что делят номер с другим: оставляем номер
-- тому, кто создан раньше (он «первый»), второму даём новый.
WITH dubli AS (
    SELECT id,
           number,
           row_number() OVER (PARTITION BY number ORDER BY created_at, id) AS poryadok
      FROM public.orders
     WHERE number IS NOT NULL AND number <> ''
), lishnie AS (
    SELECT id, number, row_number() OVER (ORDER BY id) AS smeshenie
      FROM dubli
     WHERE poryadok > 1
)
UPDATE public.orders o
   SET legacy_number = l.number,
       number = (910000 + l.smeshenie)::text
  FROM lishnie l
 WHERE o.id = l.id;

-- Теперь номер уникален. Пустой номер остаётся возможным (один удалённый в CRM
-- заказ без номера), поэтому индекс частичный.
CREATE UNIQUE INDEX IF NOT EXISTS orders_number_unique
    ON public.orders (number)
 WHERE number IS NOT NULL AND number <> '';

-- Старый номер тоже ищем: по нему приходят письма и звонки за прошлые годы.
CREATE INDEX IF NOT EXISTS orders_legacy_number_idx
    ON public.orders (legacy_number) WHERE legacy_number IS NOT NULL;
