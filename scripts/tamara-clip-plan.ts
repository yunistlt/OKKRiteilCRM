/** Индекс варианта: меняется раз в 3 дня по дате утра, круг — 90 дней. */
function rotation(date: string, size: number): number {
    const day = Math.floor(Date.parse(`${date}T00:00:00Z`) / 86_400_000);
    return Math.floor(day / 3) % size;
}

function idleVariant(date: string): string {
    return IDLE_VARIANTS[rotation(date, IDLE_VARIANTS.length)];
}

