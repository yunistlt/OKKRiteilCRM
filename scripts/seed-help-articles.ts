async function main() {
    const { supabase } = await import('../utils/supabase');
    const { generateEmbedding } = await import('../lib/embeddings');

    console.log(`Статей: ${ARTICLES.length}${APPLY ? '' : ' (примерка, ничего не пишем)'}\n`);

    for (const article of ARTICLES) {
        const sections = article.content.split('\n').filter((line) => line.startsWith('## ')).length;
        console.log(`${article.slug}\n    «${article.title}» · раздел ${article.section} · подразделов ${sections}`);

        if (!APPLY) continue;

        const embedding = await generateEmbedding(`${article.title}\n\n${article.content}`);

        const { error } = await supabase.from('okk_consultant_knowledge').upsert({
            slug: article.slug,
            type: 'instruction',
            section_key: article.section,
            title: article.title,
            content: article.content,
            tags: article.tags,
            is_active: true,
            ...(embedding.length ? { embedding } : {}),
        }, { onConflict: 'slug' });

        if (error) console.error('    не сохранилась:', error.message);
        else console.log('    записана');
    }

    if (!APPLY) {
        console.log('\nЭто примерка. Чтобы записать, запустите с --apply,');
        console.log('после чего разметьте под поиск: npx tsx scripts/sync-instructions-kb.ts');
    }
}

main().catch((e) => { console.error(e.message); process.exit(1); });
